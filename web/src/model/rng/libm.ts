const DV = new DataView(new ArrayBuffer(8));

/** High 32 bits of a double's IEEE-754 pattern. */
function hiWord(x: number): number {
  DV.setFloat64(0, x, true);
  return DV.getUint32(4, true);
}

/** Low 32 bits of a double's IEEE-754 pattern. */
function loWord(x: number): number {
  DV.setFloat64(0, x, true);
  return DV.getUint32(0, true);
}

/** The double with the given 32-bit halves. */
function fromWords(hi: number, lo: number): number {
  DV.setUint32(0, lo >>> 0, true);
  DV.setUint32(4, hi >>> 0, true);
  return DV.getFloat64(0, true);
}

/** High word of `0xc018100000000000` — the exponent-bias constant. */
const K_BIAS_HI = 0xc0181000;
/** High word of `0xfffffffff8000000` — truncates a mantissa to its top 25 bits. */
const D6_MASK_HI = 0xfffffff8;
/** ln2 in two parts, as the algorithm uses it (`C6 + C7 === ln2`). */
const C6 = fromWords(0x3fe62e42, 0xf0000000);
const C7 = fromWords(0x3e5df473, 0xde6af279);
/** 2^44 and 2^45, for the table index `(2^44 + mantissa) >> 45`. */
const TWO44 = 17592186044416;
const TWO45 = 35184372088832;

/** Dekker's exact two-product error: `a*b === p + twoProdErr(a, b)`. */
function twoProdErr(a: number, b: number): number {
  const p = a * b;
  const ca = 134217729 * a; // 2^27 + 1
  const cb = 134217729 * b;
  const ah = ca - (ca - a);
  const bh = cb - (cb - b);
  const al = a - ah;
  const bl = b - bh;
  return (ah * bh - p + ah * bl + al * bh) + al * bl;
}

/**
 * `fma(a, b, c)` — the correctly rounded `a*b + c`, which JS lacks. Overflow-free for the
 * magnitudes this lane feeds it (|a*b| stays far inside the double range).
 *
 * Also used by `nrand.ts`/`mt19937.ts`, where the oracle's build *contracted* `u*u + v*v`
 * into `fma(u, u, v*v)` — see the PORT-NOTE there.
 */
export function fma(a: number, b: number, c: number): number {
  const p = a * b;
  const e = twoProdErr(a, b);
  const s = p + c;
  const bb = s - p;
  const t = p - (s - bb) + (c - bb); // exact error of fl(p + c)
  return s + (t + e);
}

/**
 * Natural logarithm, bit-identical to the oracle's libm `log()`.
 *
 * Edge cases follow the C library: `log(±0)` is -Infinity, `log(negative)` and `log(NaN)`
 * are NaN, `log(+Infinity)` is +Infinity.
 */
export function log(x: number): number {
  let ixHi = hiWord(x);
  let ixLo = loWord(x);

  // bits(x) - 2^52: negative, subnormal, inf and nan all land in the slow path
  const x2Hi = (ixHi - 0x00100000) >>> 0;
  if (x2Hi >= 0x7fe00000) {
    if (Number.isNaN(x)) return x;
    if (x === 0) return -Infinity;
    if (x < 0) return NaN;
    if ((x2Hi | 0) >= 0) return x; // +Infinity
    // subnormal: force the exponent to 1, subtract one, continue with those bits
    const shifted = fromWords(0x3ff00000 | ixHi, ixLo) - 1.0;
    ixHi = (hiWord(shifted) + 0xc0200000) >>> 0;
    ixLo = loWord(shifted);
  }

  // k = floor(log2 x) + 1, i.e. the 64-bit sum's arithmetic shift by 52, done on the high word
  const k = ((ixHi + K_BIAS_HI) | 0) >> 20;

  const mantHi = ixHi & 0x000fffff;
  const mant = mantHi * 4294967296 + ixLo; // exact: < 2^52
  const idx = Math.floor((TWO44 + mant) / TWO45);
  const invc = LOG_TAB_INVC[idx]!;
  const logcHi = LOG_TAB_LOGC_HI[idx]!;
  const logcLo = LOG_TAB_LOGC_LO[idx]!;
  const z = fromWords(0x3ff00000 | mantHi, ixLo);

  const d1 = fma(z, invc, -1.0); // r, product rounded once
  const d16 = fma(d1, LOG_POLY[1]!, LOG_POLY[0]!);
  const d19 = d1 + LOG_POLY[3]!;
  const d21 = d1 + LOG_POLY[5]!;
  let d4 = d1 * d1;
  const d18 = fma(d1, d19, LOG_POLY[2]!);
  const d20 = fma(d1, d21, LOG_POLY[4]!);
  d4 = d4 * d16;
  d4 = d4 * d18;
  d4 = d4 * d20;

  if (k === 0) {
    // x in [0.5, 2): split r so nothing is lost to rounding
    const d5 = invc * z;
    const d6 = d5 - 1.0;
    const d5e = fma(invc, z, -d5); // exact error of the product
    const rHi = fromWords(hiWord(d6) & D6_MASK_HI, 0);
    let d2 = d5e + (d6 - rHi);
    let out = rHi + logcHi;
    d2 = d2 + logcLo;
    d2 = d2 + d4;
    out = out + d2;
    return out;
  }

  const kf = k;
  let d2 = fma(kf, C7, logcLo);
  const d3 = fma(kf, C6, logcHi);
  d2 = d2 + d4;
  return d3 + (d1 + d2);
}

