/**
 * Natural exponential, bit-identical to the oracle's libm `exp()`.
 *
 * Transcribed from the shipped machine code; the algorithm and the two traps (an *integer*
 * add of the bit patterns for the `2^q` scale, and the two fused halves of `128/ln2`) are
 * documented in this file's header and in `src/model/rng/native/raw/apple_exp_impl.h`.
 *
 * Edge cases follow the C library: `exp(+Infinity)` is `+Infinity`, `exp(-Infinity)` is 0,
 * `exp(NaN)` is NaN, `exp(±0)` is 1, and results below `2^-1022` are subnormals (`exp(x)`
 * underflows to 0 for `x < -745.25`).
 */
export function exp(x: number): number {
  const hi = hiWord(x);
  const lo = loWord(x);

  // if (bits(x) >= 0x40862e42fefa39f0) — unsigned, so this also catches every negative x
  if (hi > T_HI_HI || (hi === T_HI_HI && lo >= T_HI_LO)) {
    // if (signed(bits(x)) >= signed(0xc0874a0000000000)) — i.e. x > -745.25, +inf, any NaN
    if ((hi | 0) >= T_NEG_HI_SIGNED) {
      if (!(x < 0)) return x * DBL_MAX;
      // the csel: -inf gets a zero (no underflow flag), any other huge negative 2^-1022
      const s = hi >= 0xfff00000 ? 0 : S_TAIL_HI;
      const d = fromWords(s, 0);
      return d * d;
    }
  }

  const t = x * EXP_LN2HI_N;
  // fcvtms + scvtf: the conversion to an integer and back drops -0's sign
  const n = Math.floor(t) + 0;
  const z = t - n;
  const e1 = fma(-x, EXP_LN2HI_N, t); // t - x*ln2hiN, fused (fmsub)
  const tail = fma(x, EXP_LN2LO_N, -e1); // x*ln2loN - e1, fused (fnmsub)

  const j = n & 127;
  const tab = EXP_TAB[j]!;
  const a = tab[0];
  const b = tab[1];

  const d16 = z + EXP_C0;
  const s1 = b + tail;
  const d17 = z + EXP_C1;
  const r = z + s1;
  const d18 = fma(r, d16, EXP_C2);
  const d19 = fma(r, d17, EXP_C3);
  let p = r * EXP_C4;
  p = p * d18;
  p = p * d19;

  const q = n >> 7;

  if (q + 1022 < 0) {
    // subnormal result: the shipped code computes it in the 2^-1022 domain and scales at the
    // end, so the exponent-field add here is `(q + 1022) << 52` (an integer add of patterns)
    const d0 = fromWords((hiWord(a) + Math.imul(q + 1022, Q_SHIFT_HI)) >>> 0, loWord(a));
    const d3 = d0 + 1.0;
    let d4 = d0 - (d3 - 1.0);
    d4 = fma(d0, p, d4);
    return (d3 + d4 - 1.0) * TWO_M1022;
  }

  const scaled = fma(p, a, a); // a * (1 + p)
  return fromWords((hiWord(scaled) + Math.imul(q, Q_SHIFT_HI)) >>> 0, loWord(scaled));
}

/* ---------------------------------------------------------------- sin / cos (see above) */

const M64 = (1n << 64n) - 1n;
const SIGN64 = 1n << 63n;
const DV64 = new DataView(new ArrayBuffer(8));

/** The 64-bit IEEE-754 pattern of `x`. */
function phBits(x: number): bigint {
  DV64.setFloat64(0, x, true);
  return DV64.getBigUint64(0, true);
}

/** The double with the given 64-bit pattern. */
function phFrom(u: bigint): number {
  DV64.setBigUint64(0, u & M64, true);
  return DV64.getFloat64(0, true);
}

/** The high 64 bits of `a * b` — the machine code's `umulh`. */
function umulh(a: bigint, b: bigint): bigint {
  return ((a & M64) * (b & M64)) >> 64n;
}

/**
 * `sub Dd, Dd, Xscale` with `Xscale = clz << 52`: an *integer* subtract of the double's bit
 * pattern, which is the exact division by 2^clz the machine code uses to undo the
 * normalisation of the Payne-Hanek mantissa (the same trick `exp` uses in reverse).
 */
function unscale(v: number, clz: bigint): number {
  return phFrom(phBits(v) - (clz << 52n));
}

/**
 * `ucvtf Dd, Xn, #fbits`: the correctly rounded `x / 2^fbits`.  JS has no exact
 * bigint->double conversion with a defined tie rule, and `Number(bigint)` would be the wrong
 * operation anyway (a bit pattern is not a value), so the rounding is done here by hand:
 * nearest, ties to even, exactly as the instruction does.
 */
function ucvtf(x: bigint, fbits: number): number {
  if (x === 0n) return 0;
  if (x < 1n << 53n) return Number(x) / 2 ** fbits;
  const shift = BigInt(x.toString(2).length - 53); // keep the top 53 bits, round on the rest
  const top = x >> shift;
  const rest = x & ((1n << shift) - 1n);
  const half = 1n << (shift - 1n);
  const m = rest > half || (rest === half && (top & 1n) === 1n) ? top + 1n : top;
  return (Number(m) * 2 ** Number(shift)) / 2 ** fbits;
}

/** The sign toggle both tails end with. */
function flip(v: number, x10: bigint): number {
  return phFrom(phBits(v) ^ (x10 & SIGN64));
}

/** `1 + z * poly_cos(z)` — the cos polynomial, in its own variable. */
function cosPoly(z: number): number {
  let p = COS_POLY[0]!;
  for (let i = 1; i < 7; i++) p = fma(z, p, COS_POLY[i]!);
  return fma(z, p, 1);
}

/** The medium-path cos tail: z = 2*(d6*d7) + d6^2, then the polynomial. */
function cosEval(d6: number, d7: number): number {
  return cosPoly(fma(d6, d6, 2 * (d6 * d7)));
}

/** The sin tail: r + r*(r^2*poly_sin(r^2)), with the reduced argument's split hi/lo. */
function sinEval(r: number, d6: number, d7: number): number {
  const z = r * r;
  let p = SIN_POLY[0]!;
  for (let i = 1; i < 6; i++) p = fma(z, p, SIN_POLY[i]!);
  return d6 + fma(r, z * p, d7);
}

/** The cos-poly Payne-Hanek continuation (0x78c): the product is squared. */
function phCosTail(x: bigint, clz: bigint, x10: bigint): number {
  const x3a = umulh(MAGIC_PI2, x);
  const x3 = umulh(x3a, x3a);
  return flip(cosPoly(unscale(ucvtf(x3, 58), clz + clz)), x10);
}

/** The sin-poly Payne-Hanek continuation (0x674). */
function phSinTail(x: bigint, clz: bigint, x10: bigint): number {
  const x4 = umulh(MAGIC_PI2, x);
  return flip(
    sinEval(
      unscale(ucvtf(x4, 61), clz),
      unscale(ucvtf(x4 & 0xffff000000000000n, 61), clz),
      unscale(ucvtf(x4 & 0x0000ffffffffffffn, 61), clz),
    ),
    x10,
  );
}

/**
 * The shared Payne-Hanek reduction for `|x| >= 524288.61698514968`.  `ux` is `bits(x)` for
 * `sin` (which extracts the sign itself) and `bits(|x|)` for `cos`; `wantSin` selects sin's
 * `b.mi` / cos's `b.pl` continuation choice.
 */
function phReduce(ux: bigint, wantSin: boolean): number {
  const e = Number(((ux & ~SIGN64) >> 52n) - 0x3ffn);
  const x9 = (SIGN64 | (ux << 11n)) & M64;
  const k = e >> 6;
  const s = e & 63;
  const w0 = TAB[15 - k]!;
  const w1 = TAB[16 - k]!;
  const w2 = TAB[17 - k]!;
  const w3 = TAB[18 - k]!;
  let x4: bigint;
  let x5: bigint;
  let x6: bigint;
  if (s) {
    const t = BigInt(64 - s);
    x4 = ((w0 >> t) | (w1 << BigInt(s))) & M64;
    x5 = ((w1 >> t) | (w2 << BigInt(s))) & M64;
    x6 = ((w2 >> t) | (w3 << BigInt(s))) & M64;
  } else {
    x4 = w1;
    x5 = w2;
    x6 = w3;
  }
  // the 192x64-bit product's top 128 bits: `umulh`/`mul`/`adc`
  const h4 = umulh(x4, x9);
  const l5 = (x5 * x9) & M64;
  const a = h4 + l5;
  const x0 = a & M64;
  const x1 = (umulh(x5, x9) + ((x6 * x9) & M64) + (a > M64 ? 1n : 0n)) & M64;
  // the quadrant: the one's complement, the sign-to-apply, and which tail runs
  const x2c = ((x1 >> 61n) & 1n) === 1n ? M64 : 0n;
  const x10 = (wantSin ? ux ^ x1 : x1 ^ ((x1 << 1n) & M64)) & SIGN64;
  const test = (((x1 << 2n) ^ (x1 << 1n)) & SIGN64) !== 0n;
  const cosTail = wantSin ? test : !test;
  const v = (x1 ^ x2c) & 0x1fffffffffffffffn;
  // v is never 0 here (the product's top word is >= 83000 for |x| >= 2^19), so clz <= 61
  const clz = BigInt(64 - v.toString(2).length);
  const x1n = ((v << clz) | ((x0 ^ x2c) >> (64n - clz))) & M64;
  return cosTail ? phCosTail(x1n, clz, x10) : phSinTail(x1n, clz, x10);
}

/** `frintn`: round to nearest, ties to even (JS's `Math.round` breaks ties away from zero). */
function rint(x: number): number {
  const f = Math.floor(x);
  const d = x - f;
  if (d > 0.5) return f + 1;
  if (d < 0.5) return f;
  return f % 2 === 0 ? f : f + 1;
}

/**
 * `rint` followed by the machine code's integer conversion (`fcvtns`/`fcvtzs`): an out-of-range
 * operand **saturates** on ARM, and the shipped float functions depend on it — past ~2^63 the
 * reduced argument is meaningless and only the quadrant's low bits are read at all.  A plain
 * `BigInt(value)` would keep the whole magnitude and read *different* parity bits, which is
 * visible for `|x| > 1e19` (e.g. `sincosf(3.4e38)`).
 */
function toInt64(v: number): bigint {
  if (v >= 9223372036854775808) return 9223372036854775807n;
  if (v <= -9223372036854775809) return -9223372036854775808n;
  return BigInt(v);
}

/**
 * Sine, bit-identical to the oracle's libm `sin()`.
 *
 * Edge cases follow the C library: `sin(±0)` is ±0, `sin(±Infinity)` and `sin(NaN)` are NaN
 * (`x - x`).
 */
export function sin(x: number): number {
  if (x === 0) return x;
  const ax = Math.abs(x);
  if (ax <= PI4) return sinEval(x, 0, x);
  if (ax < THRESH) {
    const n = rint(x * INV_PI2);
    const i = BigInt(n);
    const r = x - n * PI2_HI;
    const d6 = r - n * PI2_MID;
    const d7 = r - d6 - n * PI2_MID - n * PI2_LO;
    const x10 = (i << 62n) & SIGN64;
    const d = i & 1n ? cosEval(d6, d7) : sinEval(d6 + d7, d6, d7);
    return flip(d, x10);
  }
  if (!(ax < Infinity)) return x - x;
  return phReduce(phBits(x), true);
}

/**
 * Cosine, bit-identical to the oracle's libm `cos()`.
 *
 * Edge cases follow the C library: `cos(±0)` is 1, `cos(±Infinity)` and `cos(NaN)` are NaN.
 */
export function cos(x: number): number {
  const ax = Math.abs(x);
  if (ax <= PI4) return cosEval(ax, 0);
  if (ax < THRESH) {
    const n = rint(ax * INV_PI2);
    const i = BigInt(n);
    const r = ax - n * PI2_HI;
    const d6 = r - n * PI2_MID;
    const d7 = r - d6 - n * PI2_MID - n * PI2_LO;
    const x10 = ((i ^ (i >> 1n)) << 63n) & SIGN64;
    const d = i & 1n ? sinEval(d6 + d7, d6, d7) : cosEval(d6, d7);
    return flip(d, x10);
  }
  if (!(ax < Infinity)) return ax - ax;
  return phReduce(phBits(ax), false);
}

