/** FRINTA + FCVTAS: round to nearest, ties away from zero.  `|t| <= 2^15` here, so the
 *  `+ 0.5` is exact and the truncation reproduces the machine's pair. */
function powfRintA(t: number): number {
  return t >= 0 ? Math.floor(t + 0.5) : Math.ceil(t - 0.5);
}

/**
 * 0x168..0x198, the negative-base exponent test: `|y|`, clamped to 2^24, is an integer?
 * Returns -1 when it is not (the machine's 0x244 NaN) and its parity otherwise — so anything
 * at or above 2^24 counts as even, which is a property of the shipped code, not of the model.
 */
function powfYParity(w1: number): number {
  const ay = w1 & 0x7fffffff;
  if (ay < 0x3f800000) return -1;
  const sc = f32From(Math.min(ay, 0x4b800000));       // csel w3, w3, w5, ls + fmov
  const n = Math.trunc(sc);                           // frintz + fcvtzs
  if (n !== sc) return -1;                            // fcmp s2, s1 / b.ne
  return n & 1;                                       // tbz/tbnz w5, #0
}

/** 0x1d0: `x` is `±0` or `±inf` (a NaN `x` is handled by the callers). */
function powfZero(w0: number, w1: number, w7: number): number {
  const sc = f32From(Math.min(w1 & 0x7fffffff, 0x4b800000));
  const n = Math.trunc(sc);
  const keep = n === sc && (n & 1) !== 0;             // an odd integer keeps x's sign
  let s0 = keep ? f32From(w0) : Math.abs(f32From(w0));  // 0x208: fabs
  if ((w1 & 0x80000000) !== 0) s0 = 1 / s0;           // 0x210/0x214: fdiv
  return Math.fround(s0);
}

/** 0x50..0x108: the 128-scaled log reduction, the exp assembly, one narrowing. */
function powfFast(w0: number, y: number, w7: number): number {
  const m = (w0 - POWF_LOG_BIAS) >>> 0;
  const idx = (m >>> 16) & 0x7f;
  const hi = m & 0xff800000;                          // the binade bits of `m`
  const w4 = (w0 - hi) >>> 0;
  const k = hi >> 16;                                 // `asr w2, w2, #16`, sign-extending
  const z = f32From(w4);                              // `fcvt d2, s2`
  const r = fma(z, POWF_LOG_INVC[idx]!, -1);          // `fnmsub`: Dn*Dm - Da
  const d7 = POWF_LOG_LOGC[idx]! + k;                 // `fadd d7, d7, scvtf(k)`
  const r2 = r * r;
  const d3 = fma(r, POWF_LOG_POLY[0]!, POWF_LOG_POLY[1]!);
  const d5 = fma(r, POWF_LOG_POLY[2]!, POWF_LOG_POLY[3]!);
  const l128 = fma(fma(d3, r2, d5), r, d7);           // == 128 * log2(base)
  let t = y * l128;                                   // `fmul d3, d1, d0`
  if (!(t <= POWF_T_CLAMP)) t = POWF_T_CLAMP;         // `fmin d3, d3, 2^15`
  if (!(t >= -POWF_T_CLAMP)) t = -POWF_T_CLAMP;       // `fmax d3, d3, -2^15`
  const nd = powfRintA(t);                            // `frinta` + `fcvtas`
  const n = BigInt(nd);
  const pat = (POWF_EXP_TAB[Number(n & 127n)]! + ((n << 45n) & M64)) & M64;
  const d3v = phFrom(pat);                            // `fmov d3, x1`
  const f = t - nd;
  const p = fma(POWF_EXP_POLY[0]!, f, POWF_EXP_POLY[1]!);
  const res = fma(p * f, d3v, d3v);                   // `d3 + r*poly*d3`
  return f32From((f32Bits(res) ^ w7) >>> 0);          // `fcvt s0, d0` then `eor.8b`
}

/**
 * `x ** y` for float32 operands, bit-identical to the oracle's libm `powf()`.
 *
 * Transcribed from the shipped machine code; the algorithm, the two tables and the three traps
 * are documented in this file's header and in `src/model/rng/native/raw/apple_powf_impl.h`.
 *
 * Edge cases follow the C library: `powf(1, y)` and `powf(±1, ±inf)` are `1.0f`,
 * `powf(x, ±0)` is `1.0f`, `powf(x, ±inf)` is `+inf`/`+0` by `|x|` (the mask path),
 * `powf(±0, y<0)` is `±inf` with the sign from an odd integer `y`, and `powf(x<0, y)` is NaN
 * unless `y` is an integer.
 */
export function powf(x: number, y: number): number {
  if (x === 1) return x;                              // 0x14 -> 0x22c (the `fmul` is skipped)
  if (y === 1) return Math.fround(x * 1);             // 0x1c -> 0x224: x * 1.0f
  let w0 = f32Bits(x);
  const w1 = f32Bits(y);
  let w7 = 0;
  const w2 = ((w1 & 0x7fffffff) - 1) >>> 0;
  if (w2 >= POWF_FLT_MAX_BITS) {
    // 0x10c: y is +-0, +-inf or NaN
    if ((w2 | 0) > 0x7f7fffff) return y;              // signed: NaN y -> return y
    if (w2 > 0x7f7fffff) return f32From(0x3f800000);  // +-0 / +-inf -> 1.0f
    const ax = w0 & 0x7fffffff;
    if (ax === 0) return powfZero(w0, w1, 0);
    if (ax > 0x7f800000) return Math.fround(x * 1);   // NaN x
    if (ax === 0x3f800000) return f32From(0x3f800000); // |x| == 1
    // y = +-inf, |x| neither 0 nor 1: |y| with the sign of ((|x| - 1) ^ y) inverted
    const mask = ((ax - 0x3f800000) ^ w1) >> 31;      // 0 or -1
    return f32From((f32Bits(Math.abs(y)) & ~mask) >>> 0);
  }
  if (((w0 - 0x800000) >>> 0) >= 0x7f000000) {
    // 0x150: x is not a positive normal
    const ax = w0 & 0x7fffffff;
    const w3 = (ax - 1) >>> 0;
    if (w3 >= POWF_FLT_MAX_BITS) {
      if ((w3 | 0) > 0x7f7fffff) return Math.fround(x * 1); // 0x1d0: NaN x
      return powfZero(w0, w1, w7);                          // +-0 / +-inf
    }
    if ((w0 & 0x80000000) !== 0) {
      // x < 0: only an integer y is real, and only an odd one keeps the sign
      const par = powfYParity(w1);
      if (par < 0) return f32From(0x7fc00000);        // 0x244: `inf - inf`
      if (par === 1) w7 = 0x80000000;
    }
    w0 = ax;                                          // 0x1a0: continue with |x|
    if (w0 >= 0x800000) return powfFast(w0, y, w7);
    // 0x1b4: normalise the positive subnormal (`orr.8b` with 1.0f, `fsub`, pattern minus
    // 0.5f's pattern) — all three steps are exact, so the fast path sees a fake binade
    const t = Math.fround(f32From((w0 | 0x3f800000) >>> 0) - 1);
    w0 = (f32Bits(t) - 0x3f000000) >>> 0;
    return powfFast(w0, y, w7);
  }
  return powfFast(w0, y, w7);
}

/* ---------------------------------------------------------------- atan2f (see above) */

/**
 * The oracle's `atan2f`'s polynomial in the reduced ratio `r` (`|r| <= 1`).
 *
 * Nine constants, four quadratics in `u = r*r`, two `fmla.2d`-fused steps per pair and a final
 * `fmul.2d` chain: `T8*(u^2+T0 u+T2)(u^2+T4 u+T6)*(u^2+T1 u+T3)(u^2+T5 u+T7)*r`.  The *grouping
 * and the order of the last three multiplies are load-bearing* (`(F0*F2)*T8` is rounded before
 * it meets `(F1*F3)*r`), and each `fma` is a hardware `fmla.2d`, so `T + (u + A)*u` is one
 * rounding.  `libm.ts`'s `fma` is the exact `a*b + c`, verified against the hardware.
 */
function atan2fPoly(r: number): number {
  const T = ATAN2F_POLY;
  const u = r * r;
  const f0 = fma(u + T[0]!, u, T[2]!); // `T2 + (u + T0)*u`
  const f1 = fma(u + T[1]!, u, T[3]!);
  const f2 = fma(u + T[4]!, u, T[6]!);
  const f3 = fma(u + T[5]!, u, T[7]!);
  return (f0 * f2 * T[8]!) * ((f1 * f3) * r);
}

/**
 * `atan2(y, x)` for float32 operands, bit-identical to the oracle's arm64 `atan2f`.
 *
 * Transcribed from the shipped machine code; the algorithm, the ladder and the three traps are
 * documented in this file's header and in `src/model/rng/native/raw/apple_atan2f_impl.h`.  The
 * constants come from `native/gen_atan2f_table.py`, which decodes the `adr`/`adrp`+`add`/
 * `ldr <label>` displacements that read them out of `raw/atan2f_bytes.bin`.
 *
 * The shape is a four-arm ladder on float comparisons of `y` against `x` and `-x` — the ratio is
 * always the *reduced* one, so `|r| <= 1` in every arm — plus the axis/quadrant boundaries,
 * which answer with a constant:
 *
 *   `-x < y < x`        : `P(y/x)`            (`x > 0`, `|y| < x`)
 *   `y < x <= -y`       : `-pi/2 - P(x/y)`    (and `-pi/4` when `-x === y`)
 *   `y >= x > -y`       : `pi/2 - P(x/y)`
 *   `y > x`, `y >= -x`  : `x <= 0`: `sign(y)*pi + P(y/x)`, or `+-ATAN2F_PI_HI` when
 *                         `|y/x| < 2^-22` (and `+3pi/4` when `-x === y`)
 *   `y === x`           : `pi/4`, `-3pi/4` for `y < 0`, and the origin's `+-0` / `+-pi`
 *   unordered (NaN)     : `y + x`
 *
 * Traps, all measured (see the header): the polynomial is only *float* accurate (0.36 ulp), so
 * this is **not** `f32(atan2)` (they differ by 1 ulp on ~15-20 % of arguments); the `x <= 0`
 * small-`|r|` arm answers `f32(pi)`-toward-zero-ish `+2^-32`, not `pi`, which is where arm64's
 * `atan2f(0, -1) == 0x40490fda` comes from; and the ladder's `b.pl`/`b.mi` are `N`-based, so
 * `!(a < b)` is taken for unordered too — the NaN answer is only reached through the
 * `y >= x` half, which is what the branch order below preserves.
 */
export function atan2f(y: number, x: number): number {
  y = Math.fround(y);
  x = Math.fround(x);
  const wy = f32Bits(y);

  if (!(y < x)) {
    // 0x11c: y >= x, or unordered (the ARM `b.pl` is N-based, so NaN lands here too)
    if (y === x) {
      // 0x20c: the y == x diagonal
      if (!(y >= 0)) return f32From(f32Bits(ATAN2F_NEG_3PI4));
      if (y !== 0) return f32From(f32Bits(ATAN2F_PI4));
      // y == x == 0: +-0, or +-pi when x is a negative zero
      if ((f32Bits(x) & 0x80000000) !== 0) return f32From(f32Bits(smallPi(wy)));
      return y; // `b 0xb0`: s0 is still the argument
    }
    if (y !== y || x !== x) return Math.fround(y + x); // 0x24c: NaN -> fadd s0, s0, s1
    if (!(-x < y)) {
      // 0x188: x <= 0 and y <= -x
      if (-x === y) return f32From(f32Bits(ATAN2F_3PI4)); // 0x204
      const r = y / x;
      if (Math.abs(r) < ATAN2F_SMALL) return f32From(f32Bits(smallPi(wy)));
      return f32From(
        f32Bits(atan2fPoly(r) + ((wy & 0x80000000) !== 0 ? ATAN2F_NEG_PI : ATAN2F_PI)),
      );
    }
    // 0xf0: -x < y, so |x| < y (and y > 0)
    return f32From(f32Bits(ATAN2F_HPI - atan2fPoly(x / y)));
  }

  if (!(-x < y)) {
    // 0xb8: y < x and y <= -x
    if (-x === y) return f32From(f32Bits(ATAN2F_NEG_PI4)); // 0x114
    return f32From(f32Bits(ATAN2F_NEG_HPI - atan2fPoly(x / y)));
  }
  // 0x20: y < x and -x < y
  return f32From(f32Bits(atan2fPoly(y / x)));
}

/** `|r| < 2^-22` in the `x <= 0` arm: `+-ATAN2F_PI_HI`, the sign taken from `y`'s bit pattern. */
function smallPi(wy: number): number {
  return (wy & 0x80000000) !== 0 ? -ATAN2F_PI_HI : ATAN2F_PI_HI;
}
