/**
 * Lane W1d — `log`, transcribed from the oracle's libm.
 *
 * PORT-NOTE(W1d/log-is-transcribed-not-approximated): `nrand()` (`utils/misc.cc`) and
 * `gsl_ran_ugaussian()` both feed `log()` a value in (0,1) and the result goes straight into
 * the model's arithmetic, so a 1-ulp difference changes logged bytes. Measured against the
 * oracle (macOS 26.5.2, arm64, this machine's libSystem), over the corpora in
 * `tests/rng.test.ts` plus a 180,000-value sweep:
 *
 *   `Math.log` (V8)                — 1 ulp off native on ~4.6% of sampled inputs
 *   fdlibm `e_log.c`               — ~5.7% off
 *   Arm optimized-routines `log`   — ~0.1% off (all 12 order/fma variants tried)
 *   a *correctly rounded* `log`    — still 1 ulp off on 0.06% (179,891/180,000); the
 *                                    oracle's libm is very accurate but not correctly rounded
 *
 * No approximation matches, so this is a transcription of the shipped function, instruction
 * by instruction, plus its data tables (`./appleLogTable.ts`, extracted from the running
 * libSystem — see `src/model/rng/native/README.md` for the extraction and verification
 * chain, which includes the C transcription that was diffed against the native `log` first).
 *
 * The algorithm: k = floor(log2 x) + 1, z = x / 2^(k-1) in [1,2); table index
 * `(2^44 + mantissa) >> 45` in 0..128 picks `invc ~ 1/c` and a two-part log(c) (for i >= 64
 * the stored value is log(c) - ln2 — that is what makes the k = 0 branch, i.e. x in
 * [0.5, 2), work); r = z*invc - 1 with one fused rounding; a factored polynomial
 * r^2(c0 + c1 r)(c2 + c3 r + r^2)(c4 + c5 r + r^2); and a split final sum. The k = 0 branch
 * masks r to 25 mantissa bits and adds the exact product error back, so nothing is lost to
 * rounding near log(x) = 0.
 *
 * JS has no `fma`, and the original's single-rounding fused steps are load bearing. `fma()`
 * below emulates it: Dekker/Knuth two-product gives the exact product, two-sum the exact
 * error of `+ c`, and both error terms are folded back in. Verified 0 mismatches against the
 * hardware `fma` on 2,000,000 random triples in these ranges, and the port reproduces the
 * native `log` bit-for-bit on every sampled input (203,640 of them).
 *
 * `sqrt` needs no such treatment: IEEE-754 requires it to be correctly rounded, and V8's is.
 *
 * PORT-NOTE(W1d/log-is-platform-specific): this is *this* platform's libSystem. A golden
 * recorded on another OS/CPU (glibc, or Apple Intel) could differ by an ulp, so the port
 * follows the machine the oracle was recorded on — the same rule `rand`/`drand48` follow.
 *
 * ---------------------------------------------------------------------------------------
 * `exp` (W1d follow-up): same story, measured the same way, and the numbers are in PARITY.md
 * (the libm census). The oracle's `exp` is **not** correctly rounded — over 8,261 corpus
 * values it matches the correctly rounded `e^x` on 8,255 (99.93 %), and V8's `Math.exp`
 * matches it on 7,876 (95.4 %) — so it is transcribed too, from its own machine code
 * (`native/raw/dump_exp_data.c`, `raw/expdis.s`). The algorithm is
 *
 *   t = x * 184.66496523378731 (128/ln2, high), n = floor(t), z = t - n
 *   tail = the exact residual of that reduction (two fused steps, one per half of 128/ln2)
 *   r = z + (table[n & 127].b + tail)
 *   p = C4 * r * (r*(z + C0) + C2) * (r*(z + C1) + C3)          -- e^(r*ln2/128) - 1
 *   exp(x) = table[n & 127].a * (1 + p) * 2^(n >> 7)
 *
 * with the 2^q scale applied by *adding q to the exponent field* (`q << 52` added to the bit
 * pattern — `asuint64` arithmetic, not an FP add) and a separate branch that computes the
 * subnormal results in the 2^-1022 domain. Two traps, both documented in
 * `native/raw/apple_exp_impl.h`: the exponent-field add is an integer add, and LLVM's
 * `fmsub Dd,Dn,Dm,Da` is `Da - Dn*Dm` while `fnmsub` is `Dn*Dm - Da` (settled by compiling
 * all three spellings and reading the encodings back — `raw/fmaenc2.c`).
 *
 * Verified: the C transcription of the same disassembly is bit-exact on the whole corpus and
 * on a 320,121-value sweep, and this port reproduces every corpus value (`tests/rng.test.ts`).
 *
 * ---------------------------------------------------------------------------------------
 * `sin` / `cos` (W1d follow-up: the rest of the libm census).  Both are on the model's
 * *frozen* motion path (`agent.cc:1150-1151` computes `dx = -dpos*sin(yaw()*DEGTORAD)`,
 * `dz = -dpos*cos(...)`) and in the camera (`CameraController.cc:78-80`), the census says
 * neither is correctly rounded (96.10 % / 96.14 %, max 1 ulp, against a `decimal` reference
 * at +40 digits), so they are transcribed the same way -- from the shipped machine code
 * (`native/raw/dump_libm2.c` -> `raw/sincos_bytes.bin`, tables generated by
 * `native/gen_sincos_table.py`, C transcription `raw/apple_sincos_impl.h` diffed against the
 * corpus before this port).  The algorithm, and the four traps:
 *
 *   |x| <= pi/4            sin(x) = x + x^3*poly_sin(x^2)
 *   |x| < 524288.61698514968   r = x - n*(pi/2) with a three-part pi/2 (exact subtraction),
 *                              reduced through a 6-coefficient sin or 7-coefficient cos tail
 *   else                   Payne-Hanek: a 1/pi fixed-point table (walked *backwards* by
 *                          `e >> 6`), a 192x64-bit product via `umulh`/`mul`/`adc`, then
 *                          the quadrant's tail and a `pi/2 * 2^63` fixed-point multiply
 *
 *  * the mask+normalise is not a scale change: after dropping the three quadrant bits the
 *    value is normalised to [2^63, 2^64) with `clz`, and the continuations undo that factor
 *    by subtracting `clz << 52` from the *bit pattern* of the converted double -- an integer
 *    subtract on a double register, i.e. an exact division by a power of two.  The cos
 *    continuation subtracts `2 * clz << 52`, because its value is squared.
 *  * the Payne-Hanek windows are little-endian slices of 1/pi (`ASC_TAB[15-k .. 18-k]`).
 *  * both sign flips are bit-pattern XORs (`eor.16b`, and `add d0, d0, +-0.0` for cos),
 *    never FP operations.
 *  * the flip is applied exactly once, where the machine code applies it.
 *
 * ---------------------------------------------------------------------------------------
 * `pow` (W1d follow-up: the last function of the libm census).  `pow` is on three genome
 * paths and in `utils/distributions.cc` (`Patch::setPoint`'s GAUSSIAN), the census says the
 * oracle's `pow` is not correctly rounded (4,373/4,471 = 97.81 %, V8 4,084 = 91.3 %), so it
 * gets the same treatment: a transcription of the shipped machine code
 * (`native/raw/dump_libm2.c` -> `raw/pow_bytes.bin` + `raw/pow_tables.bin`, tables extracted
 * and checked by `native/gen_pow_table.py`, C transcription `raw/apple_pow_impl.h` diffed
 * against the corpus before this port, 4,471/4,471 and 189,368/189,368 of a wide sweep).
 *
 * Unlike `exp`/`log`, `pow` does not call them: it inlines its *own* log reduction and its own
 * exp, with its own tables (both ~170 kB away from its code, reached by `adrp`+`add`):
 *
 *   log2 x (the 129-entry table, index = the rounded top 7 mantissa bits)
 *     k = ((int64)(bits x + 0xc018100000000000)) >> 52      ; floor(log2 x) + 1
 *     invc = LOG_INVC[i]; z = 1.f; r = invc*z - 1 (+ its exact product error)
 *     log2(1+r)/r = A + B r + C r^2 + r^3*(... poly ...)    ; A = 1/ln2, B = -1/(2 ln2), ...
 *     loghi = ((k + LOG_LOGC[i]) + <two terms>)             ; then `& 0xfffffffffffffffe`
 *     loglo = ((k - loghi + LOG_LOGC[i] + <two terms>)) + LOG_LOGC_LO[i] + <low part>
 *
 *   exp2(y*log2 x)
 *     t = (y*128) * loghi, residual = its exact product error + (y*128)*loglo
 *     n = floor(t), z = t - n, j = n & 127
 *     r = z + (residual - EXP_TAB[j].corr)                  ; *subtracted*, unlike `exp`
 *     poly = r * ((((c0*z + c1)*z + c2)*r + c3)*r + c4)
 *     result = (2^(n>>8) + EXP_TAB[j].x) * (1 + poly) * 2^((n>>7) - (n>>8))
 *
 * Three traps, all settled by experiment on the corpus rather than by reading:
 *
 *  * the exp assembly is bit-pattern arithmetic, not floating point: the `2^(n>>8)` term is
 *    the *pattern* `(n << 44) & 0xfff0000000000000` (a bare exponent field, biased later by
 *    adding the table entry's *pattern* -- the integer add also supplies the +1023 bias), the
 *    final scale is `((n << 45) & mask) - ((n << 44) & mask)` added to 1.0's pattern, and the
 *    negative base's sign is XORed into the first of those patterns.  Swapping that integer
 *    add for an FP multiply moves 4,262 of the 4,471 corpus values.
 *  * the log table's entries are *not* two little-endian doubles: the first 8 bytes are two
 *    32-bit halves packed `{ high word of invc, high word of logc_lo }` and the code reads
 *    only those halves (the low halves are zero by construction).  `invc` is a coarse
 *    hand-chosen reciprocal (within 2.4e-4 of 1/(1+i/128)) that only has to keep |r| under
 *    1/256; the accuracy lives in `logc_hi + logc_lo`, which is the *exact* `-log2(invc)`
 *    (minus 1 for the index >= 64 entries, the usual `k = floor(log2 x) + 1` convention).
 *    Dropping the logc_lo column moves 108 corpus values, dropping the exp table's correction
 *    1,055, and dropping the `& 0xfffffffffffffffe` on loghi 28.
 *  * the fast path is only for a positive normal `x` and a `y` in [2^-65, 2^64) (its second
 *    guard is an unsigned 64-bit subtract, so every negative `y` takes the ladder), and the
 *    *signed* `y` then drives the exponent arithmetic -- `t` is negative for a negative `y`
 *    and the two-shift exponent assembly handles a negative `n` directly, so no reciprocal is
 *    needed.  The ladder's `|y|` is only used for the range tests and the parity test
 *    (`fcvtzs` of `|y|` clamped to 2^53), which is what makes `y` is an odd integer`
 *    answerable for a negative base.
 *
 * ---------------------------------------------------------------------------------------
 * `powf` (the same follow-up: the *float* overload, which is what the two `_powf` sites in
 * the model really call -- `distributions.cc:41`'s `pow( e, rightTop/rightBottom )` inside
 * `normalPDF`/`getNormal`, and `Genome.cc:502`'s `pow( fabs(cosa), MISC_INVIS_SLOPE )`).
 * `pow` is **not** a stand-in for it: measured on the two sites' own argument domains, the
 * double transcription and V8's `Math.pow` are bit-identical to *each other* on all 797,034
 * pairs and each disagrees with the shipped `powf` on 0.13-0.90 % of them, all 1 ulp -- the
 * same "the float overload is its own function" finding `sinf`/`cosf` produced.  So `powf`
 * is transcribed from its own machine code (`native/raw/dump_libm4.c` -> `raw/powf_bytes.bin`
 * + `raw/powf_tables.bin`, tables extracted and checked by `native/gen_powf_table.py`, C
 * transcription `raw/apple_powf_impl.h` diffed against the 7,325-row corpus before this port).
 *
 * The shape is the same as `pow`'s -- an inlined log reduction with a table, an inlined exp
 * with another, everything in *double* until one `fcvt` at the end -- but every constant is
 * 128-scaled and the float side is only ever an *index*:
 *
 *   m = bits(x) - 0x3f338000
 *   i = (m >> 16) & 0x7f                      ; the 7-bit bin index
 *   k = asr32(m & 0xff800000, 16)             ; 128 * the binade (plus the bin's carry)
 *   w4 = bits(x) - (m & 0xff800000)           ; the residual as a *float* pattern, 1.mantissa
 *   z = (double) float(w4); r = z*invc[i] - 1 ; an `fnmsub` -- LLVM's `Dn*Dm - Da` order
 *   L = k + logc[i] + ((c0*r + c1)*r^2 + (c2*r + c3))*r
 *     = 128*log2(x)                           ; `logc[i]` is exactly `-128*log2(invc[i])`,
 *                                             ; so `L`'s terms cancel nothing
 *   t = (double)y * L, clamped to +-2^15; n = rinta(t); f = t - n; j = n & 0x7f
 *   bits = POWF_EXP_TAB[j] + (n << 45)        ; ONE 64-bit integer add, in % 2^64
 *   result = float( (double)bits * (1 + f*(e0*f + e1)) )   ; then `eor.8b` applies the sign
 *
 * Three traps:
 *
 *  * `L` is 128-scaled, so `powf` computes `2^(t/128)`, not `2^t`: the exp table's entries are
 *    `bits(2^(j/128)) - (j << 45)`, which is what makes the single `+ (n << 45)` exact (the
 *    subtraction never borrows, because `2^(j/128) - 1 > j/128` on [0,127]).
 *  * `fnmsub d0, d2, d0, d3` is `z*invc - 1`, the opposite of what the ARM manual's naming
 *    suggests (the same trap the `exp`/`pow` transcriptions document).  Written as
 *    `1 - z*invc` the correction has the wrong sign: measured on the corpus, that moves
 *    rows whose `z` is not exactly on the lattice (the model's own domain included).
 *  * the fast path never forms a reciprocal for a negative base and has no `|y|` at all: the
 *    sign for "negative base, odd integer exponent" is XORed into the *result pattern*
 *    (`eor.8b`) after the narrowing, and the ladder's answer for `|x| == 1` is `+-1.0f` with
 *    `y = +-inf`, `+0`/`-0`, `+inf`/`-inf` answered by a *bit mask*, not by arithmetic.
 *
 * PORT-NOTE(W1d-fu/math-pow-is-engine-version-dependent) — `pow` and `powf` above: how *far*
 * these transcriptions sit from V8's `Math.pow` is a property of V8, not of the port, and V8
 * moved under this repo.  Measured by walking the two committed corpora (`tests/rng.test.ts`
 * re-derives it on every run; `tools/measure_powf.ts` prints the `powf` line), rows on which
 * `Math.pow` disagrees with the *recorded oracle* bits:
 *
 *            `Math.pow` != oracle          V8 12.4   V8 13.6   V8 14.6
 *            `pow`  (4,471 rows)               387         9         9
 *            `powf` (7,325 rows)               196        42        42
 *
 * (node 22.22.2 / 24.21.0 / 26.7.0 — the first is the runtime an agent session gets, the other
 * two what a login shell resolves to through nvm's `default -> 24`.)  Both ports are off on
 * **0 rows under all three**: the transcription is the oracle's function whatever the engine
 * does.  The lane's tests therefore assert the *differential* contract — the oracle bit-for-bit
 * on every recorded row, and the oracle's side (never the engine's) wherever the engine
 * disagrees — with the engine-pinned counts left as a direction (`> 0`) rather than an equality.
 * An equality here is a claim about V8, and it is what turned `tests/rng.test.ts` red when the
 * shell's node switched from 22 to 24 with no change in this file.  (`native/raw/libm_census.out`
 * and the census' `V8` columns in `PARITY.md` are the same kind of number: a record of what one
 * V8 build did at census time, not a live assertion.)
 */

