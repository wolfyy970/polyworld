/** bit patterns of the constants `pow` compares against (see the PORT-NOTE). */
const P_SIGN = 0x8000000000000000n;
const P_ONE = 0x3ff0000000000000n;
const P_INF = 0x7ff0000000000000n;
const P_MANT = 0x000fffffffffffffn;
/** the u64 `2^52` the subnormal test compares the pattern against (the double 2^-1022). */
const P_2P52 = 0x0010000000000000n;
const P_2P53 = 0x4340000000000000n;
/** the mask the two exponent shifts of the exp assembly end with. */
const P_EXP_FIELD = 0xfff0000000000000n;

/** `1 / x` as the machine code's `fdiv` for a zero or infinite base. */
function pDiv(x: number): number {
  return 1 / x;
}

/** `pow`'s `2^(t/128)` (0x570..0x608), entered with `t` and its exact residual. */
function powExp2(t: number, residual: number, xsign: bigint): number {
  if (t > POW_T_MAX) return pOverflow(xsign);
  if (t < POW_T_MIN) return pUnderflow(xsign);
  const n = Math.floor(t);
  const z = t - n;
  const ni = BigInt(n);
  const tab = POW_EXP_TAB[Number(ni & 127n)]!;
  const r = residual - tab[1] + z;
  let p = fma(POW_EXP_POLY[0]!, z, POW_EXP_POLY[1]!);
  p = fma(p, z, POW_EXP_POLY[2]!);
  p = fma(p, r, POW_EXP_POLY[3]!);
  p = fma(p, r, POW_EXP_POLY[4]!);
  p = r * p;
  // the exponent-field assembly: 2^(n>>8) as a bare pattern (XORed with the negative base's
  // sign), integer-added to the table entry's pattern -- that add is also what supplies the
  // +1023 bias -- then scaled by 2^((n>>7)-(n>>8)), built the same way
  const hiBits = (ni << 44n) & P_EXP_FIELD;
  const loBits = (((ni << 45n) & P_EXP_FIELD) - hiBits) & M64;
  const base = phFrom((phBits(phFrom(hiBits ^ xsign)) + phBits(tab[0])) & M64);
  const scaled = fma(base, p, base);
  return scaled * phFrom((loBits + P_ONE) & M64);
}

/** `pow`'s log2 x (0x444..0x560) followed by its exp2. */
function powLog(ux: bigint, y: number, xsign: bigint): number {
  const mant = ux & P_MANT;
  const i = Number((((mant + 0x100000000000n) & 0x1fe00000000000n) >> 41n) >> 4n);
  const k = Number(BigInt.asIntN(64, ux + POW_K_BIAS) >> 52n);
  const invc = POW_LOG_INVC[i]!;
  const z = phFrom(P_ONE | mant);
  const prod = invc * z;
  const r = prod - 1;
  const zhi = phFrom(phBits(z) & 0xffffffffffe00000n);
  const perr = fma(invc, z - zhi, fma(invc, zhi, -prod));
  let d3 = fma(r, POW_LOG_POLY[0]!, POW_LOG_POLY[1]!);
  d3 = fma(r, d3, POW_LOG_POLY[2]!);
  d3 = fma(r, d3, POW_LOG_POLY[3]!);
  d3 = fma(r, d3, POW_LOG_POLY[4]!);
  let d4 = r * r;
  d4 = d4 * d4;
  d3 = d4 * d3;
  // log2(1+r)/r = A + B r + C r^2 + ..., carried as an accurate two-part value: every fused
  // step's exact error is recovered with an fnmsub and folded into the low part
  let d6 = fma(POW_LOG_H0, r, POW_LOG_H1);
  let d7 = fma(POW_LOG_H0_LO, r, POW_LOG_H1_LO);
  let d5 = d6 - POW_LOG_H1;
  d5 = fma(POW_LOG_H0, r, -d5);
  d7 = fma(POW_LOG_H0, perr, d7);
  d7 = d5 + d7;
  d4 = fma(d6, r, POW_LOG_A);
  d5 = fma(d7, r, POW_LOG_A_LO);
  d7 = d4 - POW_LOG_A;
  d7 = fma(d6, r, -d7);
  d5 = fma(d6, perr, d5);
  d5 = d7 + d5;
  d6 = d4 * r;
  d5 = d5 * r;
  d7 = fma(d4, r, -d6);
  d5 = fma(d4, perr, d5);
  d7 = d7 + d5;
  // the hi/lo split: the shipped code drops loghi's last mantissa bit first
  const tail = POW_LOG_LOGC[i]!;
  const loghi = phFrom(phBits((k + tail + d6) + d3) & POW_LOG_HI_MASK);
  const loglo = (((k - loghi + tail) + d6) + d3) + POW_LOG_LOGC_LO[i]! + d7;
  const y128 = y * POW_SCALE;
  const t = y128 * loghi;
  return powExp2(t, fma(y128, loglo, fma(y128, loghi, -t)), xsign);
}

/** `pow`'s exp2 called with `1/2^1022` squared: the underflow path (0x7ac). */
function pUnderflow(xsign: bigint): number {
  const t = phFrom(POW_UNDER_MUL);
  return t * phFrom(xsign | phBits(t));
}

/** `pow`'s exp2 called with `DBL_MAX` rounded up: the overflow path (0x7d0). */
function pOverflow(xsign: bigint): number {
  const t = phFrom(POW_OVER_MUL);
  return t * phFrom(xsign | phBits(t));
}

/** 0x444: x is a power of two, so log2 x is exact -- no log reduction at all. */
function powPowerOfTwo(ux: bigint, y: number, xsign: bigint): number {
  const d = BigInt.asIntN(64, ux - P_ONE);
  if (d === 0n) return phFrom(xsign | P_ONE);
  const t0 = Number(d) * 2 ** -45; // `scvtf d0, x0, #45` == 128 * log2|x|
  const t = t0 * y;
  return powExp2(t, fma(t0, y, -t), xsign);
}

/** 0x444's entry point: split on the mantissa and take the log or the exact shortcut. */
function powFromBits(ux: bigint, y: number, xsign: bigint): number {
  if ((ux & P_MANT) !== 0n) return powLog(ux, y, xsign);
  return powPowerOfTwo(ux, y, xsign);
}

/** 0x628: everything the fast path excludes. */
function powSpecial(x: number, y: number): number {
  const ux = phBits(x);
  const uy = phBits(y);
  const one = (sign: bigint) => phFrom(sign | P_ONE);
  const invalid = () => Infinity - Infinity;

  if (ux === P_ONE) return x; // 0x62c
  if (uy === P_ONE) return x === x ? x : x + x; // 0x638..0x760

  const axb = ux & 0x7fffffffffffffffn;
  const ayb = uy & 0x7fffffffffffffffn;
  const ax = phFrom(axb);
  const ay = phFrom(ayb);
  const Y_HUGE = phFrom(POW_Y_HUGE);
  const Y_TINY = phFrom(POW_Y_TINY);
  let xsign = 0n;

  /** 0x714: x is +-0 (or +-inf), so the result is +-0 / +-inf or the reciprocal. */
  const xZero = (d0: number): number => {
    if (ay >= 1) {
      const clamp = phFrom(ayb < P_2P53 ? ayb : P_2P53); // 0x71c..0x724
      if (Math.trunc(clamp) === clamp && (BigInt(Math.trunc(clamp)) & 1n) === 1n) {
        return (uy & P_SIGN) === 0n ? d0 : pDiv(d0); // an odd integer keeps x's sign
      }
    }
    const even = phFrom(axb); // 0x740: only |x| survives
    return (uy & P_SIGN) === 0n ? even : pDiv(even);
  };

  /** 0x6a4: the |y| range tests, then the log path (via the subnormal normaliser). */
  const yRange = (uxs: bigint, sign: bigint): number => {
    if (ay > Y_HUGE) {
      // 0x798: |y| > 2^64 -- only the comparison of |x| with 1 decides
      if (y < 0) {
        if (ax === 1) return one(sign);
        return ax > 1 ? pUnderflow(sign) : pOverflow(sign);
      }
      if (ax === 1) return one(sign);
      return ax > 1 ? pOverflow(sign) : pUnderflow(sign);
    }
    if (ay < Y_TINY) {
      // 0x7e8: |y| < 2^-65 -- the result is 1 +- the smallest step, never 1 exactly
      const lo = one(sign);
      const hi = phFrom(sign | 0x3be0000000000000n);
      if (y >= 0) {
        if (ax === 1) return one(sign);
        return ax > 1 ? lo + hi : lo - hi;
      }
      if (ax === 1) return one(sign);
      return ax > 1 ? lo - hi : lo + hi;
    }
    if (uxs >= P_2P52) return powFromBits(uxs, y, sign);
    // 0x6cc: a subnormal base is normalised by folding it into the exponent field
    const norm = phFrom(uxs | P_ONE) - 1;
    return powFromBits((phBits(norm) + POW_ZERO_BIAS) & M64, y, sign);
  };

  if (ayb === 0n) return one(xsign); // 0x64c: pow(x, +-0) == 1, even for NaN x
  if (ayb >= P_INF) {
    // 0x6e4: y is +-inf or NaN
    if (ayb > P_INF) return y + y; // NaN
    if (axb === 0n) return xZero(x);
    if (axb > P_INF) return x + x; // NaN
    const d = BigInt.asIntN(64, axb - P_ONE);
    if (d === 0n) return one(xsign);
    // `bic x0, x4, x0, asr #63`: +inf iff |x| - 1 and y have the same sign, else +0
    const sameSide = ((d ^ uy) >> 63n) & 1n;
    return phFrom(sameSide === 1n ? 0n : P_INF);
  }
  if (axb === 0n) return xZero(x); // 0x65c
  if (axb >= P_INF) {
    // 0x710: |x| is inf (or NaN)
    if (axb > P_INF) return x + x;
    return xZero(x);
  }
  if ((ux & P_SIGN) === 0n) return yRange(ux, xsign); // 0x668: x > 0
  // x < 0: only an integer y has a real result, and only an odd one keeps the sign
  if (ay < 1) return invalid(); // 0x66c
  {
    const clamp = phFrom(ayb < P_2P53 ? ayb : P_2P53); // 0x674..0x680
    if (Math.trunc(clamp) !== clamp) return invalid(); // 0x684..0x68c
    if ((BigInt(Math.trunc(clamp)) & 1n) === 1n) xsign = P_SIGN; // 0x694..0x698
  }
  return yRange(axb, xsign);
}

/**
 * `x ** y`, bit-identical to the oracle's libm `pow()`.
 *
 * Transcribed from the shipped machine code; the algorithm and the three traps are documented
 * in this file's header and in `src/model/rng/native/raw/apple_pow_impl.h`.
 *
 * Edge cases follow the C library: `pow(x, ±0)` and `pow(1, y)` are 1, `pow(±0, y<0)` is
 * ±Infinity (the sign from an odd integer y), `pow(-0, odd integer)` is -0, `pow(x<0, y)` is
 * NaN unless y is an integer, `pow(±Infinity, y<0)` is +0, and the overflow/underflow cases
 * return ±Infinity / ±0 with the odd-integer sign applied.
 */
export function pow(x: number, y: number): number {
  const ux = phBits(x);
  const uy = phBits(y);
  // the dispatch: both guards are unsigned 64-bit compares, so any negative y falls through
  if (BigInt.asUintN(64, ux - P_2P52) >= 0x7fe0000000000000n) return powSpecial(x, y);
  if (BigInt.asUintN(64, uy - 0x3be0000000000000n) > 0x0810000000000000n) return powSpecial(x, y);
  return powFromBits(ux, y, 0n);
}

