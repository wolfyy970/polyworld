const DV32 = new DataView(new ArrayBuffer(4));

/** The float32 bit pattern of `x` (`x` must already be float32-valued). */
function f32Bits(x: number): number {
  DV32.setFloat32(0, x, true);
  return DV32.getUint32(0, true);
}

/** The float32 with the given bit pattern. */
function f32From(u: number): number {
  DV32.setUint32(0, u >>> 0, true);
  return DV32.getFloat32(0, true);
}

/** `eor` on the double's bit pattern — a sign toggle when the mask is 2^63. */
function xorBits(v: number, mask: bigint): number {
  return phFrom(phBits(v) ^ mask);
}

/** The shipped `sin(r)` tail: `r + r^3*c2 + r^5*(c1 + r^2*c0)`, the machine code's steps. */
function sinfSinPoly(r: number): number {
  const z = r * r;
  const r3 = r * z;
  const a = fma(z, SINF_SIN_POLY[0]!, SINF_SIN_POLY[1]!);
  const r5 = z * r3;
  const b = fma(r3, SINF_SIN_POLY[2]!, r);
  return fma(r5, a, b);
}

/** The shipped `cos(r)` tail: `1 + z*(z^2*(z*c0 + c1) + (z*c2 + c3))`, `z = r^2`. */
function sinfCosPoly(r: number): number {
  const z = r * r;
  const a = fma(z, SINF_COS_POLY[0]!, SINF_COS_POLY[1]!);
  const b = fma(z, SINF_COS_POLY[2]!, SINF_COS_POLY[3]!);
  const c = z * z;
  const d = fma(c, a, b);
  return fma(z, d, 1);
}

/** The pi/2-reduction tail: tail by bit 0 of the quadrant, sign flip by bit 1. */
function sinfQuadrant(r: number, i: bigint): number {
  const mask = ((i >> 1n) << 63n) & SIGN64;
  const out = (i & 1n) !== 0n ? sinfCosPoly(r) : sinfSinPoly(r);
  return Math.fround(xorBits(out, mask));
}

/**
 * The large-argument (mod pi) tail both table paths share.  `d4` is `x*hi` (plus the `0.5`
 * cosf adds), `d5` is `x*lo`.  The sign is an XOR of `r`'s *pattern*, so it rides through the
 * polynomial as a `±r` factor.
 */
function sinfPiTail(d4: number, d5: number): number {
  const nd = rint(d4);
  const n = toInt64(nd);
  const r = d4 - nd + d5;
  const sr = xorBits(r, (BigInt.asUintN(64, n) << 63n) & SIGN64);
  const z = r * r;
  const a = z + SINF_SINPI_POLY[0]!;
  const b = z + SINF_SINPI_POLY[1]!;
  const p = fma(z, a, SINF_SINPI_POLY[2]!);
  const q = fma(z, b, SINF_SINPI_POLY[3]!);
  return Math.fround(sr * p * (SINF_SINPI_POLY[4]! * q));
}

/**
 * Sine of a float32 argument, bit-identical to the oracle's libm `sinf()` — the C++ `float`
 * overload `CameraController.cc:78-80` actually calls.
 *
 * This is not `Math.fround( sin( x ) )`: the double transcription rounded to float32 disagrees
 * with the shipped `sinf` on 304 of the 5,016 corpus arguments (6.1 %), because the float32
 * argument can sit close enough to a midpoint of the float result that the intermediate double
 * rounding decides it.  The algorithm (see `src/model/rng/native/raw/apple_sinf_impl.h`):
 *
 *   |x| < 2^-12     fmaf(x, 2^26, x) * 2^-26, all in single precision
 *   |x| < pi/4      r + r^3*c2 + r^5*(c1 + r^2*c0), 3 coefficients, in double
 *   |x| < 120       n = rint(x * 2/pi), r = x - n*pi/2 (one fused step), then the quadrant
 *   otherwise       the 1/pi table: `n = rint(x*hi)`, `r = frac + x*lo`, then `sin(pi*r)/r`
 *
 * Unlike the double `sin`, the medium reduction uses a *single-part* pi/2 (there is no
 * Payne-Hanek path at all) and the large-argument reduction multiplies by the per-exponent
 * `1/pi - A/2^s` from `SINF_TAB`, never by `1/pi` itself — see the table module and the
 * PORT-NOTE in this file's header.
 *
 * Edge cases follow the C library: `sinf(±0)` is ±0, `sinf(±Infinity)` and `sinf(NaN)` are NaN.
 */
export function sinf(x: number): number {
  const w0 = f32Bits(x) & 0x7fffffff;
  if (w0 >= 0x42f00000) {
    // |x| >= 120.0f: the table reduction (no Payne-Hanek, no two-part pi/2)
    if (w0 >= SINF_INF_BITS) return Math.fround(x - x);
    const e = SINF_TAB[(w0 >>> 24) - 0x40]!;
    return sinfPiTail(x * e[0], x * e[1]);
  }
  if (w0 < 0x3f490fdb) {
    // |x| < pi/4 (the float32 neighbour of pi/4 is the boundary the shipped code compares)
    if (w0 < 0x39800000) {
      // |x| < 2^-12: the shipped `fmadd s0, s0, s2, s0` + `fmul s0, s0, s4`, single precision.
      // `x*2^26 + x` is *exact* in double (an exponent gap of 26 below 24 significand bits),
      // so the plain expression rounds exactly once, like the fused step -- and, unlike the
      // emulated `fma`, it keeps the sign of `sinf(-0)`.
      return Math.fround((x * SINF_C2P26B + x) * SINF_C2M26);
    }
    return Math.fround(sinfSinPoly(x));
  }
  const t = x * SINF_INV_PI2;
  const nd = rint(t);
  return sinfQuadrant(fma(-nd, SINF_PI2_HI, x), toInt64(nd));
}

/**
 * Cosine of a float32 argument, bit-identical to the oracle's libm `cosf()`.
 *
 * The same shape as `sinf` with `|x|` from the start, and two differences: the table path
 * starts at 2^26 (120..2^26 subtracts a *two-part* pi/2 instead) and the quadrant index is
 * `n + 1`, because `cos(x) = sin(x + pi/2)` and only the index's low two bits are ever read.
 * The large-argument path adds the `0.5` that makes the reduction land on `x/pi + 1/2`.
 *
 * `Math.fround( cos( x ) )` disagrees with the shipped `cosf` on 135 of the corpus's 5,016
 * arguments (2.7 %).
 *
 * Edge cases follow the C library: `cosf(±0)` is 1, `cosf(±Infinity)` and `cosf(NaN)` are NaN.
 */
export function cosf(x: number): number {
  const ax = Math.abs(x);
  const w0 = f32Bits(ax);
  if (w0 >= 0x42f00000) {
    if (w0 >= 0x4c800000) {
      // |x| >= 2^26: the table reduction, with the +1/2 of the cos identity
      if (w0 >= SINF_INF_BITS) return Math.fround(ax - ax);
      const e = SINF_TAB[(w0 >>> 24) - 0x40]!;
      const d4 = ax * e[0] + 0.5;
      return sinfPiTail(d4, ax * e[1]);
    }
    // 120 <= |x| < 2^26: a two-part pi/2, still one index away
    const t = ax * SINF_INV_PI2;
    const nd = rint(t);
    return sinfQuadrant(fma(-nd, SINF_PI2_LO, fma(-nd, SINF_PI2_HI, ax)), toInt64(nd) + 1n);
  }
  if (w0 < 0x3f490fdb) {
    if (w0 < 0x39800000) {
      // |x| < 2^-12: (2^26 - |x|) * 2^-26 in single precision, i.e. 1.0f
      return Math.fround(Math.fround(SINF_C2P26B - ax) * SINF_C2M26);
    }
    return Math.fround(sinfCosPoly(ax));
  }
  const t = ax * SINF_INV_PI2;
  const nd = rint(t);
  return sinfQuadrant(fma(-nd, SINF_PI2_HI, ax), toInt64(nd) + 1n);
}

/* ------------------------------------------------------------- sincosf (see above) */

/**
 * `__sincosf_stret`'s two-lane tail: `(sin, cos)` of `pi*(n + u)/2` for a reduced `u` and a
 * quadrant `n`.  The shipped code evaluates both lanes in one 2-vector pass and narrows them to
 * float32 *before* the sign is applied.
 */
function sincosfTail(u: number, n: bigint): readonly [number, number] {
  const z = u * u;
  const ev0 = fma(z, z + SINF_SINCOS_POLY[0]!, SINF_SINCOS_POLY[6]!);
  const ev1 = fma(z, z + SINF_SINCOS_POLY[1]!, SINF_SINCOS_POLY[7]!);
  const od0 = fma(z, z + SINF_SINCOS_POLY[2]!, SINF_SINCOS_POLY[8]!);
  const od1 = fma(z, z + SINF_SINCOS_POLY[3]!, SINF_SINCOS_POLY[9]!);
  let f0 = Math.fround(u * SINF_SINCOS_POLY[4]! * ev0 * od0);
  let f1 = Math.fround(SINF_SINCOS_POLY[5]! * ev1 * od1);
  if ((n & 2n) !== 0n) {
    f0 = -f0;
    f1 = -f1;
  }
  return (n & 1n) !== 0n ? [f1, -f0] : [f0, f1];
}

/**
 * `(sin x, cos x)` of a float32 argument, bit-identical to the oracle's `__sincosf_stret` — the
 * two-output entry point in the `sinf`/`cosf` unit (`sinf + 0x1ac`), **not** a pair of
 * `sinf`/`cosf` calls.
 *
 * This is the function the native `CameraController::setRotationAngle( float )` actually calls:
 * it has adjacent `sin(camrad)`/`cos(camrad)` calls and LLVM's sincos combine merges them, so
 * the shipped `libpolyworld.dylib` contains `bl ___sincosf_stret` (measured from the symbol
 * stub).  It is a *different* algorithm from the scalar pair — it reduces with the **doubled**
 * argument against the `SINF_TAB` entry (`2x*hi`, no `+0.5`), gives the medium path no `pi/2`
 * subtraction at all (`u = x*2/pi - rint(x*2/pi)`, the quadrant carries the rest) and evaluates
 * the sine and cosine lanes together — and it disagrees with `cosf` on ordinary arguments
 * (e.g. `x = -1.1122977733612061f`: `cosf` gives `0x3ee29cc2`, this gives `0x3ee29cc3`), which
 * is exactly what the recorded camera frames pin (see `L14`'s PORT-NOTE and PARITY.md).
 *
 * Edge cases follow the C library, except that the shipped code's `+-inf`/NaN row computes
 * `x - x` and then copies it into both outputs (`fsub s0, s0, s0` leaves NaN in `s0` = `v0[0]`,
 * and `mov s1, v0[0]` moves it into the cosine), so `sincosf(+-inf)` is `(NaN, NaN)`.
 */
export function sincosf(x: number): readonly [number, number] {
  const w0 = f32Bits(x) & 0x7fffffff;
  if (w0 >= 0x42f00000) {
    if (w0 >= SINF_INF_BITS) {
      const nan = Math.fround(x - x);
      return [nan, nan];
    }
    const e = SINF_TAB[(w0 >>> 24) - 0x40]!;
    const d0 = x + x; // fadd d0, d0, d0 -- the doubled argument, exact
    const d4 = d0 * e[0];
    const nd = rint(d4);
    return sincosfTail(d4 - nd + d0 * e[1], toInt64(nd));
  }
  if (w0 < 0x39800000) {
    // |x| < 2^-12, computed in single precision like the shipped code
    const cos = Math.fround(Math.fround(SINF_C2P26B - Math.abs(x)) * SINF_C2M26);
    const sin = Math.fround((x * SINF_C2P26B + x) * SINF_C2M26);
    return [sin, cos];
  }
  const t = x * SINF_INV_PI2;
  const nd = rint(t);
  return sincosfTail(t - nd, toInt64(nd));
}

