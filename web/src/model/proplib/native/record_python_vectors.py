def record(source):
    try:
        return {"source": source, "value": str(eval(source))}
    except Exception as exc:  # noqa: BLE001 - the point is to record whatever it was
        return {
            "source": source,
            "error": str(exc),
            "errorType": type(exc).__name__,
            "syntax": isinstance(exc, SyntaxError),
        }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out",
        default="src/model/proplib/native/vectors/pythonExpressions.json",
    )
    args = parser.parse_args()

    sources = []
    seen = set()
    for source in CORPUS + CURATED:
        if source in seen:
            continue
        seen.add(source)
        sources.append(source)

    fixture = {
        "formatVersion": 1,
        "python": sys.version.split()[0],
        "interpreter": "str( eval( text ) ) via src/library/proplib/interpreter.py",
        "corpusCount": len(CORPUS),
        "vectors": [record(source) for source in sources],
        "unsupportedByPort": UNSUPPORTED,
    }

    with open(args.out, "w") as handle:
        json.dump(fixture, handle, indent=2, sort_keys=False)
        handle.write("\n")

    failures = sum(1 for vector in fixture["vectors"] if "error" in vector)
    print(
        "%s: %d vectors (%d corpus, %d curated), %d runtime/syntax failures, python %s"
        % (args.out, len(fixture["vectors"]), len(CORPUS), len(CURATED), failures, fixture["python"])
    )


if __name__ == "__main__":
    main()
