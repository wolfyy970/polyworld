"""Record what the native interpreter (`src/library/proplib/interpreter.py`) answered.

Native proplib evaluates a worldfile expression by piping the Python source text
`interpreter.cc::ExpressionEvaluator::evaluate` generated to a `python3` child, which replies
with `str( eval( text ) )`. Lane L4 ports that language; this script records the native side
of the contract so the port can be compared against it instead of against my reading of
CPython's docs.

Two vector sets land in `vectors/pythonExpressions.json`:

* `vectors` — `source` (the Python text) with the `python3` outcome: `value` = `str(eval)`, or
  `error` = `str(exc)` with `errorType` and `syntax` (a `SyntaxError`'s text is not ported
  verbatim, the port only has to fail loudly). The sources are:
    - `CORPUS`: every Python text lane L4's `generatePythonExpression` produced while building
      the four recorded scenarios (both worldfiles x `--Vision False` / no override) with the
      validation pass on. Re-collect by running the port with a recording evaluator over
      `oracle/<scenario>/run/original.{wf,wfs}` (see `tests/proplib.test.ts`, band 4);
    - `CURATED`: the language's own cases — integer/float semantics and `str()` of floats,
      comparisons, boolean operators, the conditional expression, strings and escapes,
      builtins, containers and subscripts, and the runtime failures native reported as
      `[Python] <message>`.
* `unsupportedByPort` — grammar CPython evaluates but the port *refuses on purpose*
  (`lambda`, comprehensions, f-strings, `bytes`, complex literals, `%`-formatting, walrus).
  No worldfile reaches them; the fixture records that they are rejected loudly rather than
  evaluated wrongly (PORT_SPEC rule 1: never silently disagree).

Usage: `python3 src/model/proplib/native/record_python_vectors.py [--out PATH]`
"""

