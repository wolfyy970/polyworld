describe('groups grow arithmetic', () => {
  it('rounds `nsynjiperneur + remainder` to FLOAT before the double `1.e-5` promotes it', () => {
    // the case that exposed the all-double reading: 1.0f plus a remainder a hair below the
    // -1e-5 that would cancel the literal. `float( 1.0f + rem )` rounds *down* to
    // 0.99998998641967773, so the double 1.e-5 lifts the sum to just under 1 and `short(...)`
    // truncates to 0; the all-double sum is 1.00000000036 and truncates to 1
    const nsyn = f32(1.0);
    const rem = f32(-9.999636e-6);
    expect(f32(nsyn + rem)).toBe(0.9999899864196777);
    expect(synapseCountNew(nsyn, rem)).toBe(0);
    expect(toShort(nsyn + rem + 1.e-5)).toBe(1); // the arithmetic this replaced
  });

  it('truncates `synapseCount_new` toward zero (not floor) and wraps through short', () => {
    expect(synapseCountNew(f32(1.5), f32(-2.4))).toBe(0); // -0.9 truncates to 0, floor gives -1
    expect(synapseCountNew(f32(0.0), f32(0.0))).toBe(0);
    expect(synapseCountNew(f32(40000.0), f32(0.0))).toBe(40000 - 65536);
  });

  it('keeps the remainder accumulator in float', () => {
    const nsyn = f32(1.0 / 3.0);
    const scn = 0;
    expect(remainderUpdate(0, nsyn, scn)).toBe(f32(1.0 / 3.0));
    // the `nsynjiperneur - synapseCount_new` difference is computed in float too
    expect(remainderUpdate(f32(0.5), f32(7.0), 3)).toBe(f32(0.5 + f32(7.0 - 3)));
  });

  it('clamps the base local index with max<short>/min<short>', () => {
    // 0/4*8 - 6*0.5 = -3 -> clamped up to 0
    expect(neuronLocalIndexFromBase(0, 4, 8, 6)).toBe(0);
    // (3/4)*8 - 2*0.5 = 5
    expect(neuronLocalIndexFromBase(3, 4, 8, 2)).toBe(5);
    // the upper clamp is `neuronCount_from - synapseCount_new`, narrowed through short
    expect(neuronLocalIndexFromBase(3, 4, 4, 2)).toBe(2);
  });

  it('computes `td_fromto_abs` in float for all three native branches', () => {
    expect(tdFromToAbs(0.25, TdAbsBranch.UNMIRRORED)).toBe(f32(0.25));
    expect(tdFromToAbs(0.25, TdAbsBranch.MIRRORED_LOW)).toBe(0.5);
    expect(tdFromToAbs(0.75, TdAbsBranch.MIRRORED_HIGH)).toBe(0.5);
    // the result is always a float store, never a double
    const wide = f32(1.0 / 3.0);
    expect(tdFromToAbs(wide, TdAbsBranch.MIRRORED_HIGH)).toBe(f32(f32(1 - wide) * 2));
  });

  it('narrows the distortion index through `nint` and short, consuming two draws', () => {
    // `nint(a)` mentions `a` twice, and in the walk `a` holds a `range()` *call*, so the compiled
    // walk consumes TWO draws per passing connection: the first feeds the sum, the second only
    // its sign. `distortionIndex( drawForSum, drawForSign, td_fromto_abs, neuronCount_from )`.
    //
    // `nint(0.5)` is 0 — an exact half rounds toward zero (the macro adds 0.499999999)
    expect(distortionIndex(0.5, 0.5, 1, 1)).toBe(0);
    expect(Math.round(0.5)).toBe(1);
    expect(distortionIndex(0.49, 0.49, 1, 2)).toBe(1); // nint(0.98) = 1
    expect(distortionIndex(-0.5, -0.5, 1, 1)).toBe(0);
    // the sign test reads the *second* draw, the sum the first: -0.4*1*3 = -1.2, and the epsilon
    // the macro picks is what decides between trunc(-0.7) = 0 and trunc(-1.7) = -1
    expect(distortionIndex(-0.4, 0.5, 1, 3)).toBe(0);
    expect(distortionIndex(-0.4, -0.5, 1, 3)).toBe(-1);
    // the first draw alone drives the magnitude
    expect(distortionIndex(-0.4, 0.5, 1, 3)).toBe(distortionIndex(-0.4, 0.25, 1, 3));
    expect(distortionIndex(0.5, 0.5, 1, 100000)).toBe(50000 - 65536); // short(...) wraps
  });

  it('stores `stdev` as a float', () => {
    const gene = f32(1.0 / 3.0);
    const stdev = stdevOf(gene, 7.0);
    // f32(1/3) * 7 = 2.3333334028720856, rounded to the float store — *not* the double 7/3
    expect(stdev).toBe(f32(f32(1.0 / 3.0) * 7.0));
    expect(stdev).toBe(2.3333334922790527);
    expect(f32(stdev)).toBe(stdev); // i.e. the store is a float store
  });

  it('evaluates the energy formula as `a * float(n) / float(m)` — product before division', () => {
    // native (GroupsBrain.cc:616-617) is left to right; the pre-review grouping `a * (n / m)`
    // rounds to a *different float* as soon as the denominator is not a power of two
    expect(energyUseOf(12.5, 1234, 1500, 0, 0, 1024)).toBe(10.283333778381348);
    expect(f32(12.5 * f32(1234 / 1500))).toBe(10.283332824707031);
    expect(energyUseOf(0, 0, 32, 0, 0, 1024)).toBe(0);
  });
});

