/**
 * Where `run_brainprobe.sh` compiles the probe and writes its eight modes' output.
 *
 * t_d5ed17d8: this used to be ONE fixed directory (`node_modules/.cache/brainprobe`) shared by
 * every process on the checkout. Two lanes verifying at the same time both linked
 * `$OUT/brainprobe`; one `clang++` (with `-g` → `dsymutil`) then read a binary the other was
 * rewriting and the `beforeAll` below threw
 *
 *     error: cannot parse the debug map for '…/node_modules/.cache/brainprobe/brainprobe':
 *     No such file or directory
 *     clang++: error: dsymutil command failed with exit code 1
 *
 * so `tests/brain-core.test.ts` failed as a file and its 76 tests were skipped (~1 pair in 5 with
 * two concurrent full-suite runs, 1 in 2 with two concurrent single-file runs, measured).
 *
 * Keying the directory by process id — plus the vitest worker thread, since `pool: 'threads'` runs
 * every worker in one pid — isolates concurrent runs; this is the same per-process key t_37bf7212
 * gave `tests/logsCorpus.ts`'s candidate root. The directory is passed to the script as its
 * `[outdir]` argument, so the probe cannot end up writing somewhere else. `BRAINPROBE_DIR` still
 * pins a caller's own path (a known location for a human reading the probe's output) and is
 * honoured by the script as well. The only reader of these files is this test file, so no caller
 * needs to know the key.
 */
export function defaultProbeDir(cwd: string, pid: number, thread: number): string {
  const leaf = thread === 0 ? `pid-${pid}` : `pid-${pid}-t${thread}`;
  return join(cwd, 'node_modules', '.cache', 'brainprobe', leaf);
}

