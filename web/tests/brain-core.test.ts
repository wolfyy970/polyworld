/**
 * Lane L6 (brain core) — the lane's acceptance tests.
 *
 * Two layers:
 *
 *   1. **Unit tests** for the pieces that can be pinned without native: the C `%g` rounding
 *      rules, `nint`/`f32`/`toShort`, the nerve activation-buffer indirection (including the
 *      swap the models perform), `SynapseMap`'s std::map ordering, the sheets geometry
 *      (spacing/insets/absolute positions/receptive-field subsets) and the cull.
 *
 *   2. **Differential parity against the oracle's own code** (`brainprobe`, built from the
 *      native tree's `libpolyworld.dylib` by `src/model/brain/core/native/run_brainprobe.sh`).
 *      The probe drives the *real* `FiringRateModel`, `SpikingModel`, `Brain::dumpAnatomical/
 *      startFunctional/writeFunctional/dumpSynapses` over a synthetic brain it describes in a
 *      spec file; this test rebuilds that brain with the port, runs it, and diffs
 *
 *        - `run/brain/function/**`-shaped bytes (`startFunctional` + one `writeFunctional`
 *          per step + `endFunctional`),
 *        - `run/brain/synapses/**`-shaped bytes (`dumpSynapses`, after learning),
 *        - `run/brain/anatomy/**`-shaped bytes (`dumpAnatomical`),
 *        - the raw IEEE-754 bits of every activation and of every final efficacy, so a 1-ulp
 *          divergence cannot hide behind `%g`'s six digits,
 *        - `%g`/`%G`/`%f`/`%+06.4f`/`%hd`/`%ld` formatting against this machine's `printf`.
 *
 *      Three variants are diffed: `firingrate` (learning on), `taugain` (tau/gain model with
 *      a *frozen* brain, i.e. the learning loop skipped) and `spiking` (50 brain steps per
 *      world step, ~2600 `drand48` draws per step, STDP).
 *
 * The native inputs are generated by the probe's own LCG and written to the spec file, so
 * this test needs no reference data checked in; and the harness's `drand48` stand-in is
 * verified against the probe's glibc samples before it is used (see `describe('drand48')`).
 *
 * If the native tree (or its built library) is not present the differential suite is skipped
 * with a message rather than failing: the lane's contract is byte-exact parity *where the
 * oracle exists*, and a developer without the native build should still get the unit tests.
 */

