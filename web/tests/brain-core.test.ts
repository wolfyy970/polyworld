// ---------------------------------------------------------------------------
// the learning rule's clamp chain — PARITY.md's L6 mutation table's last survivor
//
// `FiringRateModel::update` / `SpikingModel::update` decay an efficacy back toward
// `0.5*maxWeight` once it is above it (0x5e8bc-0x5e8cc / 0x67cb0-0x67cc4), and the shipped code
// computes that chain in `float`, one rounding per operation, with the first product fused
// (`fmadd s16, s0, s6, s18`). The port transcribes exactly that; reverting it to the pre-sweep
// binary64 form
//
//     scaled = 1.0 - (oneMinusDecay * (Math.abs(efficacy) - halfMaxWeight)) / halfMaxWeight;
//     efficacy = f32(efficacy * scaled);
//
// used to pass in every suite, because nothing drove the site: the `models` spec's efficacies
// are all inside the clamp bound, and the hand-built drive of `t_2a625bd5` ran the model with
// the learning block gated *off* (`Brain::config.enableLearning` is derived from `learningMode`
// by `Brain::processWorldfile`, not by the model), so its efficacies came back exactly as set.
//
// `brainprobe learnclamp` now builds the input that is reachable from `update()` alone —
// constructed `|efficacy|` inside `(0.5*maxWeight, maxWeight]`, one step through the model's own
// `set_synapse -> update -> get_synapse` round trip — and writes, per synapse, the pre-clamp
// value, the value the *shipped* model stored, and the value the pre-change form would store.
// The pin below is that comparison, per bit, for all three families.
// ---------------------------------------------------------------------------

const LEARNCLAMP_TAGS = ['clampfiringrate', 'clampfiringrate2', 'clampspiking'] as const;

interface LearnClampRow {
  k: number;
  before: string;
  native: string;
  pre: string;
  differs: boolean;
}

function readLearnClamp(tag: string): {
  rows: LearnClampRow[];
  candidates: number;
  clamped: number;
  differs: number;
  identical: number;
  currentMismatches: number;
} {
  const out = { rows: [] as LearnClampRow[], candidates: 0, clamped: 0, differs: 0, identical: 0, currentMismatches: 0 };
  for (const line of readFileSync(join(PROBE_DIR, `learnclamp.${tag}.txt`), 'utf8').split('\n')) {
    if (line.startsWith('learnclamp ')) {
      const f = line.split(' ');
      out.rows.push({ k: Number(f[1]), before: f[2]!, native: f[3]!, pre: f[4]!, differs: f[5] === 'differs' });
    } else if (line.startsWith('summary ')) {
      const f = line.split(' ');
      out.candidates = Number(f[2]);
      out.clamped = Number(f[4]);
      out.differs = Number(f[6]);
      out.identical = Number(f[8]);
      out.currentMismatches = Number(f[10]);
    }
  }
  return out;
}

/**
 * The learning step with the clamp chain reverted to the pre-sweep binary64 form — the mutation
 * the table names, transcribed here from `git show HEAD:src/model/brain/core/firingRateModel.ts`
 * and `spikingModel.ts`. Every intermediate is its own expression, exactly as the pre-change code
 * wrote them, so the rounding sequence is the mutated one (a single expression would round once).
 */
function learningStepPreChange(args: {
  spiking: boolean;
  efficacyBefore: number;
  lrate: number;
  aTo: number;
  aFrom: number;
  deltaAfterDecay: number;
  maxWeight: number;
  decayRate: number;
}): number {
  const { spiking, efficacyBefore, lrate, aTo, aFrom, deltaAfterDecay, maxWeight, decayRate } = args;
  const halfMaxWeight = f32(0.5 * maxWeight);
  const oneMinusDecay = f32(1.0 - decayRate);

  let efficacy: number;
  if (spiking) {
    // pre-change: `syn.efficacy ± (0.01 + syn.delta * learningrate)`, all binary64, narrowed once
    const increment = 0.01 + deltaAfterDecay * lrate;
    efficacy = efficacyBefore >= 0 ? f32(efficacyBefore + increment) : f32(efficacyBefore - increment);
  } else {
    // pre-change: `syn.efficacy + learningrate * (aTo-0.5) * (aFrom-0.5)`, binary64, narrowed once
    efficacy = f32(efficacyBefore + lrate * (aTo - 0.5) * (aFrom - 0.5));
  }

  if (Math.abs(efficacy) > halfMaxWeight) {
    const scaled = 1.0 - (oneMinusDecay * (Math.abs(efficacy) - halfMaxWeight)) / halfMaxWeight;
    efficacy = f32(efficacy * scaled);
    if (efficacy > maxWeight) efficacy = maxWeight;
    else if (efficacy < -maxWeight) efficacy = -maxWeight;
  } else {
    if (lrate >= 0.0) efficacy = Math.max(0.0, efficacy);
    if (lrate < 0.0) efficacy = Math.min(f32(-1.e-10), efficacy);
  }
  return efficacy;
}

/** The port's own pre-clamp value for one row, from the state the port's learning loop reads. */
function portPreClampValue(args: {
  spiking: boolean;
  efficacyBefore: number;
  lrate: number;
  aTo: number;
  aFrom: number;
  deltaAfterDecay: number;
}): number {
  if (args.spiking) {
    const increment = 0.01 + f32(args.deltaAfterDecay * args.lrate);
    return args.efficacyBefore >= 0
      ? f32(args.efficacyBefore + increment)
      : f32(args.efficacyBefore - increment);
  }
  const delta = (args.aTo - 0.5) * args.lrate;
  return f32(fma64(delta, args.aFrom - 0.5, args.efficacyBefore));
}

