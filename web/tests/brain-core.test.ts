// ---------------------------------------------------------------------------
// the learning step's fused delta (`0x5e890-0x5e8ac`)
// ---------------------------------------------------------------------------
//
// `learnclamp`'s three families pin the clamp *chain*, and by construction they cannot pin the
// contraction that forms its input: their delta is `lrate * (a_to-0.5) * (a_from-0.5)` over live
// activations, and the fused and unfused deltas then differ by at most half an ulp of a product
// bounded by `maxlrate * 0.5 * 0.5` — a f32 store at `|e| ≈ 4` cannot see that. Measured on this
// tree: reverting the delta line alone left the whole suite green, 0 of the clamp family's 3,072
// driven rows separating it.
//
// `brainprobe learndelta` makes the delta exact and the product free instead:
//
//   * the destination neuron is saturated — `bias` alone holds `logistic(.)` at exactly 1.0 — so
//     `a_to - 0.5` is exactly 0.5 and the delta is the exact double `0.5 * lrate`;
//   * each row drives its own input neuron, whose activation the spec's `input` line carries at
//     full double precision, so `db = a_from - 0.5` is a free double;
//   * `lrate` is small enough that one ulp of the input's own grid moves the product by about one
//     ulp of itself, which lets the probe walk `db` onto the f32 midpoint above the stored
//     efficacy — where the fused `fmadd d17, d18, d19, d17` and the round-product-then-sum form
//     narrow to *different* floats.
//
// The mode emits only rows that separate and exits non-zero when it finds none, so this family is
// the contraction's own witness: every row here moves when the delta line is reverted.
// ---------------------------------------------------------------------------

interface LearnDeltaRow {
  k: number;
  fused: string;
  native: string;
  pre: string;
  differs: boolean;
}

function readLearnDelta(): {
  rows: LearnDeltaRow[];
  rowsCount: number;
  differs: number;
  same: number;
  saturated: number;
  currentMismatches: number;
} {
  const out = { rows: [] as LearnDeltaRow[], rowsCount: 0, differs: 0, same: 0, saturated: 0, currentMismatches: 0 };
  for (const line of readFileSync(join(PROBE_DIR, 'learndelta.txt'), 'utf8').split('\n')) {
    if (line.startsWith('learndelta ')) {
      const f = line.split(' ');
      out.rows.push({ k: Number(f[1]), fused: f[2]!, native: f[3]!, pre: f[4]!, differs: f[5] === 'differs' });
    } else if (line.startsWith('summary ')) {
      const f = line.split(' ');
      out.rowsCount = Number(f[2]);
      out.differs = Number(f[4]);
      out.same = Number(f[6]);
      out.saturated = Number(f[8]);
      out.currentMismatches = Number(f[10]);
    }
  }
  return out;
}

differential("native parity: learndelta (the learning rule's fused delta)", () => {
  let spec: Spec;
  let rows: LearnDeltaRow[];
  let counts: ReturnType<typeof readLearnDelta>;
  let port: ReturnType<typeof runPort>;

  beforeAll(() => {
    spec = readSpec('learndelta');
    counts = readLearnDelta();
    rows = counts.rows;
    port = runPort(spec);
  });

  it('drives a family whose every row separates the fused delta, and that is not vacuous', () => {
    expect(rows.length).toBe(counts.rowsCount);
    expect(rows.length).toBe(spec.dims.numSynapses);
    expect(rows.length).toBeGreaterThanOrEqual(8);
    // one input neuron per row: each `db` is its own full-precision double
    expect(spec.dims.numNeurons).toBe(2 * rows.length);
    // the mode emits only rows the contraction moves, so a family that lost its teeth — or a
    // build where the probe's own transcription re-fused the two forms — shows up here
    expect(counts.differs).toBe(rows.length);
    expect(counts.same).toBe(0);
    expect(counts.differs + counts.same).toBe(rows.length);
    // the construction's invariant, measured on the shipped model: every destination activation
    // is exactly 1.0, which is what makes the delta the exact double `0.5 * lrate`
    expect(counts.saturated).toBe(rows.length);
    // and the probe's transcription of the *shipped* arithmetic (compiled by the native
    // toolchain) agrees with the shipped model on every row — a wrong transcription would show
    // up here rather than as a passing pin
    expect(counts.currentMismatches).toBe(0);
    for (const row of rows) expect(row.differs).toBe(row.pre !== row.native);
  });

  it('matches the shipped model bit-for-bit on every driven synapse', () => {
    const mismatches = rows
      .filter((row) => floatBits(port.model.getSynapse(row.k).efficacy) !== row.native)
      .map((row) => `synapse ${row.k}: native 0x${row.native}, port 0x${floatBits(port.model.getSynapse(row.k).efficacy)}`);
    expect(mismatches.slice(0, 8)).toEqual([]);
    // eslint-disable-next-line no-console
    console.log(`learndelta: ${rows.length} driven rows, all ${counts.differs} narrowed differently by the two forms`);
  });

  it('is the mutation the table names: the round-product delta disagrees on every row, and the port follows the shipped model', () => {
    const activations = port.brain.getActivations(0, spec.dims.numNeurons);
    const mismatch: string[] = [];
    const missed: string[] = [];
    let separated = 0;
    for (const row of rows) {
      const synapse = spec.synapses[row.k]!;
      const aFrom = spec.inputs[0]![synapse.from]!;
      const aTo = activations[synapse.to]!;
      // the construction: the destination is saturated, so the delta is exactly `0.5 * lrate`
      if (aTo !== 1.0) mismatch.push(`synapse ${row.k}: destination activation ${aTo} is not exactly 1.0`);
      // (a) the port's own pre-clamp value is the probe's `fused` column, bit for bit — the fused
      // product+add the shipped `fmadd` at 0x5e8a8 performs
      const fused = portPreClampValue({
        spiking: false,
        efficacyBefore: synapse.efficacy,
        lrate: synapse.lrate,
        aTo,
        aFrom,
        deltaAfterDecay: 0,
      });
      if (floatBits(fused) !== row.fused) {
        mismatch.push(`synapse ${row.k}: port fused 0x${floatBits(fused)}, probe 0x${row.fused}`);
      }
      // (b) the mutation — `f32(syn.efficacy + learningrate * (a_to-0.5) * (a_from-0.5))`, the
      // product rounded before the add — is the probe's `pre` column, and it moves *every* row
      const mutated = learningStepPreChange({
        spiking: false,
        efficacyBefore: synapse.efficacy,
        lrate: synapse.lrate,
        aTo,
        aFrom,
        deltaAfterDecay: 0,
        maxWeight: spec.maxWeight,
        decayRate: spec.decayRate,
      });
      if (floatBits(mutated) !== row.pre) {
        mismatch.push(`synapse ${row.k}: mutation 0x${floatBits(mutated)}, probe 0x${row.pre}`);
      }
      if (floatBits(mutated) !== row.native) separated += 1;
      else missed.push(`synapse ${row.k}: the round-product delta leaves 0x${row.native} alone`);
    }
    expect(mismatch.slice(0, 8)).toEqual([]);
    expect(missed.slice(0, 8)).toEqual([]);
    expect(separated).toBe(rows.length);
  });
});

