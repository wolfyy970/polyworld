differential('libm census', () => {
  it('measures the port’s exp/logistic against the oracle’s libm', () => {
    const lines = readFileSync(join(PROBE_DIR, 'math.txt'), 'utf8').split('\n').filter((l) => l.length > 0);

    let logisticTotal = 0;
    let logisticExact = 0;
    let logisticMaxUlp = 0;
    let expTotal = 0;
    let expExact = 0;
    let expMaxUlp = 0;
    // the same probe replayed through V8's `Math.exp`, i.e. the drift this lane used to
    // carry: it stays in the measurement so the numbers in PARITY.md can be re-derived, and
    // so "the port is not V8" is asserted rather than remembered
    let v8ExpExact = 0;

    for (const line of lines) {
      const f = line.split(' ');
      if (f[0] === 'logistic') {
        const x = bitsToDouble(f[2]!);
        const expected = f[3]!;
        const got = doubleBits(logistic(x, Number(f[1])));
        logisticTotal += 1;
        if (got === expected) logisticExact += 1;
        else logisticMaxUlp = Math.max(logisticMaxUlp, ulpDistance(expected, got));
      } else {
        const x = bitsToDouble(f[1]!);
        const expected = f[2]!;
        const got = doubleBits(exp(x));
        expTotal += 1;
        if (got === expected) expExact += 1;
        else expMaxUlp = Math.max(expMaxUlp, ulpDistance(expected, got));
        if (doubleBits(Math.exp(x)) === expected) v8ExpExact += 1;
      }
    }

    // `exp` is lane L1's transcription of the oracle's libm (W1d follow-up): it is exact on
    // this probe and on its own 8,261-value corpus (`tests/rng.test.ts`), while `Math.exp` is
    // not -- the drift this lane's PARITY row used to quote. The assertions are equality, so a
    // future rewrite that reaches for `Math.exp` again fails here instead of quietly moving
    // the activation bits.
    console.log(
      `libm census: logistic ${logisticExact}/${logisticTotal} bit-exact (max ${logisticMaxUlp} ulp), ` +
        `exp ${expExact}/${expTotal} bit-exact (max ${expMaxUlp} ulp) ` +
        `[Math.exp ${v8ExpExact}/${expTotal}]`,
    );
    expect(logisticTotal).toBe(2048);
    expect(expTotal).toBe(512);
    expect(logisticExact).toBe(logisticTotal);
    expect(expExact).toBe(expTotal);
    expect(expMaxUlp).toBe(0);
    expect(v8ExpExact).toBeLessThan(expTotal);
  });
});

