differential('fma64 (native differential)', () => {
  it('reproduces the hardware fused multiply-add bit for bit', () => {
    const lines = readFileSync(join(PROBE_DIR, 'fma.txt'), 'utf8')
      .split('\n')
      .filter((l) => l.length > 0 && !l.startsWith('#'));

    let bad = 0;
    let naiveBad = 0;
    let examples = 0;
    for (const line of lines) {
      const f = line.split(' ');
      if (f[0] !== 'fma') throw new Error(`fma.txt: unknown tag ${f[0]}`);
      const a = bitsToDouble(f[1]!);
      const b = bitsToDouble(f[2]!);
      const c = bitsToDouble(f[3]!);
      const want = f[4]!;
      const got = doubleBits(fma64(a, b, c));
      if (got !== want) {
        if (examples < 5) console.log(`fma64 miss: a=${f[1]} b=${f[2]} c=${f[3]} hw=${want} port=${got}`);
        examples += 1;
        bad += 1;
      }
      // the transcription this replaced: the product rounded, then the sum rounded
      if (doubleBits(a * b + c) !== want) naiveBad += 1;
    }

    // eslint-disable-next-line no-console
    console.log(`fma census: ${lines.length - bad}/${lines.length} bit-exact (naive a*b+c wrong on ${naiveBad})`);
    expect(lines.length).toBeGreaterThan(30_000);
    expect(bad).toBe(0);
    // non-vacuity: a transcription that rounds the product first is wrong on a large fraction
    expect(naiveBad).toBeGreaterThan(1000);
  });
});

// ---------------------------------------------------------------------------
// the grow arithmetic against the native compiler (`growexpr` mode)
//
// `GroupsBrain::growSynapses` cannot be driven end-to-end until lane L5 (a native
// `GroupsGenome`) and lane L8 (`agent::config`) exist, so `brainprobe growexpr` compiles a
// transcription of each of its C expressions with the oracle's own clang++ and evaluates them
// over an enumerated grid; this test replays the inputs through `growArithmetic.ts` and
// compares the results bit-for-bit. The pre-review transcriptions are evaluated alongside, so
// the *grid's* power to catch the defect it was built for is measured rather than assumed.
// ---------------------------------------------------------------------------

differential('groups grow arithmetic (native differential)', () => {
  it('reproduces every native growSynapses expression over the probe grid', () => {
    const lines = readFileSync(join(PROBE_DIR, 'growexpr.txt'), 'utf8')
      .split('\n')
      .filter((l) => l.length > 0 && !l.startsWith('#'));

    // the arithmetic this lane shipped *before* review round 1 (the all-double sum, the extra
    // `f32` before the base-index cast, the double `(1 - td) * 2`, the double `stdev`)
    const legacyBase = (localTo: number, countTo: number, countFrom: number, scn: number): number => {
      const raw = f32(f32(f32(localTo / countTo) * f32(countFrom)) - f32(scn) * 0.5);
      return Math.max(toShort(0), Math.min(toShort(countFrom - scn), toShort(raw)));
    };
    const legacy = {
      synnew: (nsyn: number, rem: number) => toShort(nsyn + rem + 1.e-5),
      baseidx: legacyBase,
      tdabs: (td: number, branch: number) => (branch === 1 ? td * 2 : branch === 2 ? (1 - td) * 2 : td),
      stdev: (gene: number, config: number) => gene * config,
      // the pre-review grouping: `a * (n / m)` instead of native's `(a * n) / m`
      energy: (a: number, n: number, maxn: number, b: number, s: number, maxs: number) =>
        f32(f32(a * f32(n / maxn)) + f32(b * f32(s / maxs))),
      // the round-then-add reading of the `nint` macro's argument (the product materialised,
      // then the ±0.499999999 added) — `distortionIndex` before `t_7d391d0f`, and the form the
      // binary's `0x66dc0 fmadd` contracts away
      distort: (termA: number, termB: number, td: number, count: number) =>
        toShort(Math.trunc(termA * td * count + (termB * td * count < 0.0 ? -0.499999999 : 0.499999999))),
    };

    const tally = new Map<string, { rows: number; bad: number; legacyBad: number }>();
    const note = (tag: string, ok: boolean, legacyOk: boolean | null) => {
      const t = tally.get(tag) ?? { rows: 0, bad: 0, legacyBad: 0 };
      t.rows += 1;
      if (!ok) t.bad += 1;
      if (legacyOk === false) t.legacyBad += 1;
      tally.set(tag, t);
    };

    for (const line of lines) {
      const p = line.split(' ');
      switch (p[0]) {
        case 'synnew': {
          const nsyn = floatFromBits(p[1]!);
          const rem = floatFromBits(p[2]!);
          const want = Number(p[3]);
          note('synnew', synapseCountNew(nsyn, rem) === want, legacy.synnew(nsyn, rem) === want);
          break;
        }
        case 'remupd': {
          // the port's `remainderUpdate` is unchanged from the pre-review revision
          const rem = floatFromBits(p[1]!);
          const nsyn = floatFromBits(p[2]!);
          const scn = Number(p[3]);
          note('remupd', floatBits(remainderUpdate(rem, nsyn, scn)) === p[4], null);
          break;
        }
        case 'baseidx': {
          const [localTo, countTo, countFrom, scn] = p.slice(1, 5).map(Number) as [number, number, number, number];
          const want = Number(p[5]);
          note('baseidx', neuronLocalIndexFromBase(localTo, countTo, countFrom, scn) === want, legacy.baseidx(localTo, countTo, countFrom, scn) === want);
          break;
        }
        case 'tdabs': {
          const td = floatFromBits(p[1]!);
          const branch = Number(p[2]) as 0 | 1 | 2;
          const key = branch === 1 ? TdAbsBranch.MIRRORED_LOW : branch === 2 ? TdAbsBranch.MIRRORED_HIGH : TdAbsBranch.UNMIRRORED;
          note('tdabs', floatBits(tdFromToAbs(td, key)) === p[3], floatBits(legacy.tdabs(td, branch)) === p[3]);
          break;
        }
        case 'distort':
        case 'distortb': {
          // the macro holds a `range()` call, so the walk draws twice per passing connection:
          // row = <drawA_bits> <drawB_bits> <tdabs_bits> <count> <distortion>
          //
          // `distortb` is the probe's *boundary* family (`t_7d391d0f`): draws constructed so the
          // last multiply's exact product lands within ~1 ulp of the truncation boundary, i.e.
          // so that the binary's `0x66dc0 fmadd` and a round-then-add transcription give
          // different indices. The probe emits a row only when the two disagree.
          const termA = bitsToDouble(p[1]!);
          const termB = bitsToDouble(p[2]!);
          const td = floatFromBits(p[3]!);
          const count = Number(p[4]);
          note(
            p[0]!,
            distortionIndex(termA, termB, td, count) === Number(p[5]),
            legacy.distort(termA, termB, td, count) === Number(p[5]),
          );
          break;
        }
        case 'stdev': {
          note('stdev', floatBits(stdevOf(floatFromBits(p[1]!), floatFromBits(p[2]!))) === p[3], floatBits(legacy.stdev(floatFromBits(p[1]!), floatFromBits(p[2]!))) === p[3]);
          break;
        }
        case 'energy': {
          const a = floatFromBits(p[1]!);
          const n = Number(p[2]);
          const maxn = Number(p[3]);
          const b = floatFromBits(p[4]!);
          const s = Number(p[5]);
          const maxs = Number(p[6]);
          const got = energyUseOf(a, n, maxn, b, s, maxs);
          note('energy', floatBits(got) === p[7], floatBits(legacy.energy(a, n, maxn, b, s, maxs)) === p[7]);
          break;
        }
        default:
          throw new Error(`growexpr.txt: unknown tag ${p[0]}`);
      }
    }

    let rows = 0;
    for (const [tag, t] of tally) {
      rows += t.rows;
      // eslint-disable-next-line no-console
      console.log(`grow arithmetic ${tag}: ${t.rows - t.bad}/${t.rows} exact (pre-review form wrong on ${t.legacyBad})`);
      expect(t.rows).toBeGreaterThan(100);
      expect(t.bad).toBe(0);
    }

    expect(tally.size).toBe(8);
    expect(rows).toBe(lines.length);
    expect(rows).toBeGreaterThan(40_000);
    // the grid is not vacuous: it catches the defect it was written for (review round 1's
    // all-double `short( nsynjiperneur + remainder + 1.e-5 )`), which is what makes the zero
    // above evidence rather than an artefact of too few inputs
    expect(tally.get('synnew')!.legacyBad).toBeGreaterThan(0);
    // …and that the energy formula's *grouping* matters too (the product is native's first)
    expect(tally.get('energy')!.legacyBad).toBeGreaterThan(0);
    // `t_7d391d0f`: the *boundary* family, where `0x66dc0 fmadd d0, d9, d11, d0` is visible in
    // the result. The probe emits a row only where the compiled macro and the round-then-add
    // transcription disagree, so every row of it must be one the pre-change form gets wrong —
    // a vacuous family here would mean the family never reached the truncation boundary.
    expect(tally.get('distortb')!.rows).toBeGreaterThan(100);
    expect(tally.get('distortb')!.legacyBad).toBe(tally.get('distortb')!.rows);
  });
});

// ---------------------------------------------------------------------------
// the `SeedSynapsesFromRun` reader/writer pair — `Brain::dumpSynapses` ->
// `Brain::loadSynapses` -> `copySynapses` / `scaleSynapses`
//
// `Logs::brainEnd` writes `run/brain/synapses/synapses_<agent>_<stage>.txt` through
// `Brain::dumpSynapses`, and `analysis::getNervousSystem` / `analysis::copyNervousSystem` /
// `analysis::setMaxWeight` read it back through `Brain::loadSynapses` (with and without a
// rescale) and `Brain::copySynapses`. Every recorded scenario leaves `SeedSynapsesFromRun
// False`, so no golden reaches any of the three.
//
// `brainprobe synapses` drives them from the shipped library itself; its corpus is committed
// under `src/model/brain/core/native/vectors/` (so this block needs no C++ — CI, the browser
// lane and a reviewer without a native build replay the same numbers), and
// `differential('synapses vectors')` below re-runs the mode and fails if the regenerated
// corpus differs. Two families bracket the dump's loss: `synrandom` carries the efficacies a
// real brain holds (which `%g`'s six significant digits do *not* reproduce) and `synexact`
// holds decimals short enough for it to reproduce them exactly. Every value is compared as raw
// IEEE-754 bits; `syndump.<tag>.txt` is compared as bytes.
// ---------------------------------------------------------------------------

const SYNAPSE_VECTORS = join(REPO, 'src', 'model', 'brain', 'core', 'native', 'vectors');
const SYNAPSE_TAGS = ['synrandom', 'synexact'] as const;
type SynapseTag = (typeof SYNAPSE_TAGS)[number];

interface SynapseRow {
  from: number;
  to: number;
  efficacy: string;
  lrate: string;
}

interface SynapseReport {
  dump: string;
  index: number;
  dims: Dimensions;
  maxWeightBits: string;
  fileMaxWeightBits: string;
  src: SynapseRow[];
  rt: SynapseRow[];
  range: Array<{ start: number; end: number }>;
  copy: SynapseRow[];
  copyRange: Array<{ start: number; end: number }>;
  scaleMwBits: string[];
  scaleFactorBits: string[];
  scale: string[][];
  summary: { synapses: number; rtSame: number; copySame: number; scaleRows: number; scaleChanged: number };
}

function readSynapseReport(tag: SynapseTag): SynapseReport {
  const report: SynapseReport = {
    dump: readFileSync(join(SYNAPSE_VECTORS, `syndump.${tag}.txt`), 'utf8'),
    index: 0,
    dims: new Dimensions(),
    maxWeightBits: '',
    fileMaxWeightBits: '',
    src: [],
    rt: [],
    range: [],
    copy: [],
    copyRange: [],
    scaleMwBits: [],
    scaleFactorBits: [],
    scale: [],
    summary: { synapses: 0, rtSame: 0, copySame: 0, scaleRows: 0, scaleChanged: 0 },
  };

  const row = (f: string[]): SynapseRow => ({
    from: Number(f[2]),
    to: Number(f[3]),
    efficacy: f[4]!,
    lrate: f[5]!,
  });

  for (const line of readFileSync(join(SYNAPSE_VECTORS, `synapses.${tag}.txt`), 'utf8').split('\n')) {
    if (line.length === 0 || line.startsWith('#')) continue;
    const f = line.split(' ');
    switch (f[0]) {
      case 'family':
        if (f[1] !== tag) throw new Error(`synapses.${tag}.txt: family ${f[1]}`);
        break;
      case 'dumpindex':
        report.index = Number(f[1]);
        break;
      case 'dims':
        report.dims.numNeurons = Number(f[1]);
        report.dims.numInputNeurons = Number(f[2]);
        report.dims.numOutputNeurons = Number(f[3]);
        report.dims.numSynapses = Number(f[4]);
        break;
      case 'maxweight':
        report.maxWeightBits = f[1]!;
        break;
      case 'filemaxweight':
        report.fileMaxWeightBits = f[1]!;
        break;
      case 'src':
        report.src[Number(f[1])!] = row(f);
        break;
      case 'rt':
        report.rt[Number(f[1])!] = row(f);
        break;
      case 'range':
        report.range[Number(f[1])!] = { start: Number(f[2]), end: Number(f[3]) };
        break;
      case 'copy':
        report.copy[Number(f[1])!] = row(f);
        break;
      case 'copyrange':
        report.copyRange[Number(f[1])!] = { start: Number(f[2]), end: Number(f[3]) };
        break;
      case 'scalemw':
        report.scaleMwBits[Number(f[1])!] = f[2]!;
        break;
      case 'scalefactor':
        report.scaleFactorBits[Number(f[1])!] = f[2]!;
        break;
      case 'scale': {
        const m = Number(f[1]);
        (report.scale[m] ??= [])[Number(f[2])!] = f[3]!;
        break;
      }
      case 'summary':
        report.summary = {
          synapses: Number(f[2]),
          rtSame: Number(f[4]),
          copySame: Number(f[6]),
          scaleRows: Number(f[8]),
          scaleChanged: Number(f[10]),
        };
        break;
      default:
        throw new Error(`synapses.${tag}.txt: unknown tag ${f[0]}`);
    }
  }

  return report;
}

/**
 * The probe's brain, rebuilt with the port — the state `loadSynapses`/`copySynapses` land on.
 *
 * `perturbRanges` reproduces what the probe does to the brain a dump is loaded *into*: the
 * native caller (`analysis::getNervousSystem`) grows that brain from a genome first, so it
 * holds its own ranges until the load overwrites the ones it sees — which is what makes the
 * `range`/`copyrange` rows evidence about `setSynapses` rather than about the construction both
 * sides share.
 */
function buildSynapseBrain(tag: SynapseTag, perturbRanges: boolean): { brain: ProbeBrain; model: FiringRateModel; spec: Spec } {
  const spec = readSpec(tag, SYNAPSE_VECTORS);

  brainConfig.neuronModel = NeuronModelKind.FIRING_RATE;
  brainConfig.architecture = BrainArchitecture.Groups;
  brainConfig.logisticSlope = spec.logisticSlope;
  brainConfig.maxWeight = spec.maxWeight;
  brainConfig.maxbias = spec.maxBias;
  brainConfig.enableLearning = spec.enableLearning;
  brainConfig.minlrate = spec.minlrate;
  brainConfig.maxlrate = spec.maxlrate;
  brainConfig.decayRate = spec.decayRate;
  brainConfig.learningMode = LearningMode.LEARN_ALL;

  const rng = new GlibcDrand48();
  const cns = new ProbeCns(rng);
  const brain = new ProbeBrain(cns);
  cns.wire(brain);

  const model = new FiringRateModel(cns);
  brain.install(spec.dims, model);
  model.init(spec.dims, 0.1);

  // the same two calls per neuron the probe's `initNeuronAttrs(model, spec, false, false)` makes
  for (let i = 0; i < spec.dims.numInputNeurons; i++) {
    const attrs: FiringRateNeuronAttrs = { bias: 0, tau: 0, gain: 0 };
    model.setNeuron(i, attrs);
  }
  for (let i = spec.dims.numInputNeurons; i < spec.dims.numNeurons; i++) {
    const n = spec.neurons[i]!;
    const attrs: FiringRateNeuronAttrs = { bias: n.bias, tau: n.tau, gain: n.gain };
    model.setNeuron(i, attrs, n.start);
    model.setNeuronEndSynapses(i, n.end);
  }
  for (let k = 0; k < spec.dims.numSynapses; k++) {
    const s = spec.synapses[k]!;
    model.setSynapse(k, s.from, s.to, s.efficacy, s.lrate);
  }

  if (perturbRanges) {
    for (let i = 0; i < spec.dims.numNeurons; i++) {
      const n = spec.neurons[i]!;
      const attrs: FiringRateNeuronAttrs = { bias: n.bias, tau: n.tau, gain: n.gain };
      model.setNeuron(i, attrs, i, i + 1);
    }
  }

  return { brain, model, spec };
}

/** A loaded brain: the probe's dump read back through the port's `Brain::loadSynapses`. */
function loadSynapseDump(tag: SynapseTag): { brain: ProbeBrain; model: FiringRateModel; spec: Spec } {
  const built = buildSynapseBrain(tag, true);
  const file = new StringTextFile();
  file.resetForRead(readFileSync(join(SYNAPSE_VECTORS, `syndump.${tag}.txt`), 'utf8'));
  built.brain.loadSynapses(file);
  return built;
}

describe('the SeedSynapsesFromRun reader/writer pair (native vectors)', () => {
  for (const tag of SYNAPSE_TAGS) {
    describe(tag, () => {
      let report: SynapseReport;

      beforeAll(() => {
        report = readSynapseReport(tag);
      });

      it('writes the bytes the native recorder wrote (run/brain/synapses/**)', () => {
        const { brain } = buildSynapseBrain(tag, false);
        const file = new StringTextFile();
        brain.dumpSynapses(file, report.index);
        expect(file.contents()).toBe(report.dump);
      });

      it('rebuilds the probe’s own table bit for bit', () => {
        const { model } = buildSynapseBrain(tag, false);
        for (let k = 0; k < report.dims.numSynapses; k++) {
          const s = model.getSynapse(k);
          expect([s.fromneuron, s.toneuron, floatBits(s.efficacy), floatBits(s.lrate)]).toEqual([
            report.src[k]!.from,
            report.src[k]!.to,
            report.src[k]!.efficacy,
            report.src[k]!.lrate,
          ]);
        }
      });

      it('reproduces the native dump round trip bit for bit', () => {
        const { model } = loadSynapseDump(tag);
        let survived = 0;
        for (let k = 0; k < report.dims.numSynapses; k++) {
          const s = model.getSynapse(k);
          expect([s.fromneuron, s.toneuron]).toEqual([report.rt[k]!.from, report.rt[k]!.to]);
          expect(floatBits(s.efficacy)).toBe(report.rt[k]!.efficacy);
          expect(floatBits(s.lrate)).toBe(report.rt[k]!.lrate);
          if (
            floatBits(s.efficacy) === report.src[k]!.efficacy &&
            floatBits(s.lrate) === report.src[k]!.lrate
          ) {
            survived += 1;
          }
        }

        // the family bracket, measured: `synexact`'s decimals are short enough for `%g` to
        // reproduce, `synrandom`'s are not — so a reader that reformatted the values, or one
        // that kept them instead of re-reading the text, fails on one family or the other
        // eslint-disable-next-line no-console
        console.log(
          `loadSynapses ${tag}: ${survived}/${report.dims.numSynapses} values survive the dump round trip` +
            ` (native ${report.summary.rtSame})`,
        );
        expect(report.summary.synapses).toBe(report.dims.numSynapses);
        expect(survived).toBe(report.summary.rtSame);
        if (tag === 'synexact') expect(survived).toBe(report.dims.numSynapses);
        else expect(survived).toBeLessThan(report.dims.numSynapses);
      });

      it('re-derives the neuron ranges `setSynapses` re-derives, and leaves the unwired neuron alone', () => {
        const { model } = loadSynapseDump(tag);
        const state = model.rawState();
        let rewritten = 0;
        for (let i = 0; i < report.dims.numNeurons; i++) {
          const neuron = state.neuron[i]!;
          expect([neuron.startsynapses, neuron.endsynapses]).toEqual([
            report.range[i]!.start,
            report.range[i]!.end,
          ]);
          // the probe perturbs every range to `[i, i+1]` before the load, so any row that came
          // out different is one `setSynapses` rewrote
          if (report.range[i]!.start !== i || report.range[i]!.end !== i + 1) rewritten += 1;
        }

        expect(rewritten).toBeGreaterThan(0);
        // …and the last neuron has no incoming synapse, so the load must not touch it at all
        const last = report.dims.numNeurons - 1;
        expect([report.range[last]!.start, report.range[last]!.end]).toEqual([last, last + 1]);
      });

      it('copies the loaded table bit for bit, ranges included', () => {
        const loaded = loadSynapseDump(tag);
        const { brain, model } = buildSynapseBrain(tag, true);
        brain.copySynapses(loaded.brain);

        for (let k = 0; k < report.dims.numSynapses; k++) {
          const s = model.getSynapse(k);
          expect([s.fromneuron, s.toneuron, floatBits(s.efficacy), floatBits(s.lrate)]).toEqual([
            report.copy[k]!.from,
            report.copy[k]!.to,
            report.copy[k]!.efficacy,
            report.copy[k]!.lrate,
          ]);
        }

        const state = model.rawState();
        for (let i = 0; i < report.dims.numNeurons; i++) {
          expect([state.neuron[i]!.startsynapses, state.neuron[i]!.endsynapses]).toEqual([
            report.copyRange[i]!.start,
            report.copyRange[i]!.end,
          ]);
        }

        // the copy is the loaded *brain's* table, not a re-read of the file's text: on the
        // lossy family the two differ, so a `copySynapses` that re-parsed the dump would fail
        expect(report.copy.map((r) => r.efficacy)).toEqual(report.rt.map((r) => r.efficacy));
        expect(report.summary.copySame).toBe(report.dims.numSynapses);
      });

      it('rescales by the native float division in `loadSynapses( file, maxWeight )`', () => {
        const loadedState = loadSynapseDump(tag);
        const loadedBits: string[] = [];
        for (let k = 0; k < report.dims.numSynapses; k++) {
          loadedBits.push(floatBits(loadedState.model.getSynapse(k).efficacy));
        }

        // the transcription this card replaced (`t_da2ab201`-style: measure it, don't assume
        // its power): `fileMaxWeight` left as the binary64 the port's `%g` reader returns —
        // native stores the header's field in a `float` — and the quotient then computed in
        // binary64 with the product rounded to `float` only at the store
        const headerMaxWeight = /maxweight=(\S+)/.exec(report.dump)![1]!;
        const legacyFileMaxWeight = Number(headerMaxWeight);
        let legacyBad = 0;
        let rows = 0;

        for (let m = 0; m < report.scaleMwBits.length; m++) {
          const maxWeight = floatFromBits(report.scaleMwBits[m]!);
          // `Brain::loadSynapses( file, maxWeight )` divides `maxWeight` by the header's own
          // `maxweight=` field read back into a *float* and divides in `float`; the corpus
          // carries both the value (`scalefactor`) and the result, so the transcription is
          // checked against the shipped `fdiv` rather than assumed
          expect(floatBits(f32(maxWeight / f32(Number(headerMaxWeight))))).toBe(report.scaleFactorBits[m]!);

          const { brain, model } = buildSynapseBrain(tag, true);
          const file = new StringTextFile();
          file.resetForRead(report.dump);
          const header = brain.loadSynapses(file, maxWeight);
          // the header field the port hands back is the float native stores (not the binary64
          // its own `%g` reader returns)
          expect(floatBits(header.fileMaxWeight)).toBe(report.fileMaxWeightBits);

          for (let k = 0; k < report.dims.numSynapses; k++) {
            const got = floatBits(model.getSynapse(k).efficacy);
            expect(got).toBe(report.scale[m]![k]!);
            const legacy = floatBits(f32(floatFromBits(loadedBits[k]!) * (maxWeight / legacyFileMaxWeight)));
            if (legacy !== got) legacyBad += 1;
            rows += 1;
          }
        }

        // eslint-disable-next-line no-console
        console.log(
          `loadSynapses(${tag}, maxWeight): ${legacyBad}/${rows} rows separate the binary64 transcription` +
            ` (${report.scaleMwBits.length} maxWeight values)`,
        );
        expect(rows).toBe(report.summary.scaleRows);
        // the rescale actually moved efficacies (native's own count), so the rows are not all
        // "scale by a factor of one" cases
        expect(report.summary.scaleChanged).toBeGreaterThan(0);
        // measured, not assumed: the pre-change form is wrong on a large fraction of the rows,
        // which is what makes the zero-mismatch above evidence about the `float` division
        expect(legacyBad).toBeGreaterThan(0);
      });
    });
  }
});

// The committed corpus is the oracle, and this is the check that keeps it honest: the probe
// re-runs the same mode against the shipped library and its output must be byte-identical to
// what is committed. A diff here means the native build's dump/load moved — re-record with
// `src/model/brain/core/native/record_synapses_vectors.sh` and review the new numbers.
differential('synapses vectors (native differential)', () => {
  for (const tag of SYNAPSE_TAGS) {
    it(`regenerates the committed ${tag} corpus byte for byte`, () => {
      for (const name of [`spec.${tag}.txt`, `syndump.${tag}.txt`, `synapses.${tag}.txt`]) {
        expect(readFileSync(join(PROBE_DIR, name), 'utf8')).toBe(readFileSync(join(SYNAPSE_VECTORS, name), 'utf8'));
      }
    });
  }
});
