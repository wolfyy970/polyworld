class GlibcDrand48 implements RngSurface {
  private state = 0n;

  srand48(seed: number): void {
    this.state = ((BigInt(Math.trunc(seed)) << 16n) + 0x330en) & 0xffffffffffffn;
  }

  drand48(): number {
    this.state = (this.state * 0x5deece66dn + 0xbn) & 0xffffffffffffn;
    return Number(this.state) / 281474976710656; // 2^48
  }

  lrand48(): number {
    return Math.floor(this.drand48() * 2147483648);
  }

  srand(): void {
    throw new Error('harness: srand is not used by the brain');
  }

  rand(): number {
    throw new Error('harness: rand is not used by the brain');
  }

  private spare = 0;
  private hasSpare = false;

  nrand(): number {
    if (this.hasSpare) {
      this.hasSpare = false;
      return this.spare;
    }
    let u = 0;
    let v = 0;
    let s = 0;
    do {
      u = 2.0 * this.drand48() - 1.0;
      v = 2.0 * this.drand48() - 1.0;
      s = u * u + v * v;
    } while (s === 0.0 || s >= 1.0);
    const c = Math.sqrt((-2.0 * Math.log(s)) / s);
    this.spare = c * v;
    this.hasSpare = true;
    return c * u;
  }

  nrandScaled(mean: number, stdev: number): number {
    return mean + this.nrand() * stdev;
  }
}

/** A `NervousSystem` whose `Brain *` can be wired up without a genome (native `grow`). */
class ProbeCns extends NervousSystem {
  constructor(rng: RngSurface) {
    super(rng);
  }

  wire(brain: Brain): void {
    this.b = brain;
  }
}

/** A `Brain` whose dims/neural net can be set the way `GroupsBrain::grow` sets them. */
class ProbeBrain extends Brain {
  constructor(cns: NervousSystem) {
    super(cns);
  }

  install(dims: Dimensions, net: NeuronModel): void {
    const target = this.getDimensions();
    target.numNeurons = dims.numNeurons;
    target.numInputNeurons = dims.numInputNeurons;
    target.numOutputNeurons = dims.numOutputNeurons;
    target.numSynapses = dims.numSynapses;
    this._neuralnet = net;
  }
}

interface Spec {
  model: string;
  tauGain: boolean;
  frozen: boolean;
  logisticSlope: number;
  maxWeight: number;
  maxBias: number;
  enableLearning: boolean;
  minlrate: number;
  maxlrate: number;
  decayRate: number;
  scaleLatestSpikes: number;
  drandSeed: number;
  spikingParams: number;
  dims: Dimensions;
  neurons: Array<{ bias: number; tau: number; gain: number; sa: number; sb: number; sc: number; sd: number; start: number; end: number }>;
  synapses: Array<{ from: number; to: number; efficacy: number; lrate: number }>;
  inputs: number[][];
}

function readSpec(tag: string, dir = PROBE_DIR): Spec {
  const text = readFileSync(join(dir, `spec.${tag}.txt`), 'utf8');
  const spec: Spec = {
    model: tag,
    tauGain: false,
    frozen: false,
    logisticSlope: 0,
    maxWeight: 0,
    maxBias: 0,
    enableLearning: false,
    minlrate: 0,
    maxlrate: 0,
    decayRate: 0,
    scaleLatestSpikes: 0,
    drandSeed: 0,
    spikingParams: 0,
    dims: new Dimensions(),
    neurons: [],
    synapses: [],
    inputs: [],
  };

  for (const line of text.split('\n')) {
    if (line.length === 0) continue;
    const f = line.split(' ');
    switch (f[0]) {
      case 'model':
        spec.model = f[1]!;
        break;
      case 'tauGain':
        spec.tauGain = f[1] === '1';
        break;
      case 'frozen':
        spec.frozen = f[1] === '1';
        break;
      case 'logisticSlope':
        spec.logisticSlope = f32(Number(f[1]));
        break;
      case 'maxWeight':
        spec.maxWeight = f32(Number(f[1]));
        break;
      case 'maxBias':
        spec.maxBias = f32(Number(f[1]));
        break;
      case 'enableLearning':
        spec.enableLearning = f[1] === '1';
        break;
      case 'minlrate':
        spec.minlrate = f32(Number(f[1]));
        break;
      case 'maxlrate':
        spec.maxlrate = f32(Number(f[1]));
        break;
      case 'decayRate':
        spec.decayRate = f32(Number(f[1]));
        break;
      case 'scaleLatestSpikes':
        spec.scaleLatestSpikes = f32(Number(f[1]));
        break;
      case 'drandSeed':
        spec.drandSeed = Number(f[1]);
        break;
      case 'spikingParams':
        spec.spikingParams = Number(f[1]);
        break;
      case 'dims':
        spec.dims.numNeurons = Number(f[1]);
        spec.dims.numInputNeurons = Number(f[2]);
        spec.dims.numOutputNeurons = Number(f[3]);
        spec.dims.numSynapses = Number(f[4]);
        break;
      case 'neuron':
        spec.neurons[Number(f[1])!] = {
          bias: f32(Number(f[2])),
          tau: f32(Number(f[3])),
          gain: f32(Number(f[4])),
          sa: f32(Number(f[5])),
          sb: f32(Number(f[6])),
          sc: f32(Number(f[7])),
          sd: f32(Number(f[8])),
          start: Number(f[9]),
          end: Number(f[10]),
        };
        break;
      case 'synapse':
        spec.synapses[Number(f[1])!] = {
          from: Number(f[2]),
          to: Number(f[3]),
          efficacy: f32(Number(f[4])),
          lrate: f32(Number(f[5])),
        };
        break;
      case 'input':
        spec.inputs[Number(f[1])!] = f.slice(2).map(Number);
        break;
      default:
        throw new Error(`unknown spec line: ${line}`);
    }
  }

  return spec;
}

/** Rebuild the probe's brain with the port and run the same steps. */
function runPort(spec: Spec): {
  brain: ProbeBrain;
  model: NeuronModel;
  function: string;
  synapses: string;
  anatomy: string;
  activationBits: string[];
  efficacyBits: string[];
  energyUse: number;
} {
  brainConfig.neuronModel = spec.model === 'spiking'
    ? NeuronModelKind.SPIKING
    : spec.tauGain
      ? NeuronModelKind.TAU_GAIN
      : NeuronModelKind.FIRING_RATE;
  brainConfig.architecture = BrainArchitecture.Groups;
  brainConfig.logisticSlope = spec.logisticSlope;
  brainConfig.maxWeight = spec.maxWeight;
  brainConfig.maxbias = spec.maxBias;
  brainConfig.enableLearning = spec.enableLearning;
  brainConfig.minlrate = spec.minlrate;
  brainConfig.maxlrate = spec.maxlrate;
  brainConfig.decayRate = spec.decayRate;
  brainConfig.learningMode = LearningMode.LEARN_ALL;

  const rng = new GlibcDrand48();
  const cns = new ProbeCns(rng);
  const brain = new ProbeBrain(cns);
  cns.wire(brain);
  if (spec.frozen) brain.freeze();

  const model: NeuronModel = spec.model === 'spiking'
    ? new SpikingModel(cns, spec.scaleLatestSpikes)
    : new FiringRateModel(cns);
  brain.install(spec.dims, model);

  model.init(spec.dims, 0.1);

  // neurons, in the same order and with the same two calls `GroupsBrain::grow` makes
  for (let i = 0; i < spec.dims.numInputNeurons; i++) {
    const neuron = spec.neurons[i]!;
    if (spec.model === 'spiking') {
      const attrs: SpikingNeuronAttrs = { bias: 0, spikingParameterA: 0, spikingParameterB: 0, spikingParameterC: 0, spikingParameterD: 0 };
      model.setNeuron(i, attrs);
    } else {
      const attrs: FiringRateNeuronAttrs = { bias: neuron.bias, tau: 0, gain: 0 };
      attrs.bias = 0;
      model.setNeuron(i, attrs);
    }
  }
  for (let i = spec.dims.numInputNeurons; i < spec.dims.numNeurons; i++) {
    const neuron = spec.neurons[i]!;
    if (spec.model === 'spiking') {
      const attrs: SpikingNeuronAttrs = spec.spikingParams === 1
        ? { bias: neuron.bias, spikingParameterA: neuron.sa, spikingParameterB: neuron.sb, spikingParameterC: neuron.sc, spikingParameterD: neuron.sd }
        : { bias: neuron.bias, spikingParameterA: 0.02, spikingParameterB: 0.2, spikingParameterC: -65, spikingParameterD: 6 };
      model.setNeuron(i, attrs, neuron.start);
    } else {
      const attrs: FiringRateNeuronAttrs = { bias: neuron.bias, tau: neuron.tau, gain: neuron.gain };
      model.setNeuron(i, attrs, neuron.start);
    }
    model.setNeuronEndSynapses(i, neuron.end);
  }
  for (let k = 0; k < spec.synapses.length; k++) {
    const s = spec.synapses[k]!;
    model.setSynapse(k, s.from, s.to, s.efficacy, s.lrate);
  }

  const functional = new StringTextFile();
  brain.startFunctional(functional, 42, 13);

  rng.srand48(spec.drandSeed);
  const activationBits: string[] = [];
  for (let step = 0; step < spec.inputs.length; step++) {
    model.setActivations(spec.inputs[step]!, 0, spec.inputs[step]!.length);
    brain.update(false);
    brain.writeFunctional(functional);

    const activations = brain.getActivations(0, spec.dims.numNeurons);
    for (let i = 0; i < spec.dims.numNeurons; i++) activationBits.push(doubleBits(activations[i]!));
  }
  brain.endFunctional(functional, 1.5);

  const synapseFile = new StringTextFile();
  brain.dumpSynapses(synapseFile, 42);

  const anatomyFile = new StringTextFile();
  brain.dumpAnatomical(anatomyFile, 42, 1.5);

  const efficacyBits: string[] = [];
  for (let k = 0; k < spec.dims.numSynapses; k++) efficacyBits.push(floatBits(model.getSynapse(k).efficacy));

  return {
    brain,
    model,
    function: functional.contents(),
    synapses: synapseFile.contents(),
    anatomy: anatomyFile.contents(),
    activationBits,
    efficacyBits,
    energyUse: brain.getEnergyUse(),
  };
}

function doubleBits(v: number): string {
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, v);
  return (BigInt(view.getUint32(0)) << 32n | BigInt(view.getUint32(4))).toString(16).padStart(16, '0');
}

/** Bits -> value, for the probe's raw-bit dump. */
function bitsToDouble(bits: string): number {
  const view = new DataView(new ArrayBuffer(8));
  view.setUint32(0, Number.parseInt(bits.slice(0, 8), 16));
  view.setUint32(4, Number.parseInt(bits.slice(8), 16));
  return view.getFloat64(0);
}

/**
 * Compare two runs value by value, by ULP distance, treating the sign separately (IEEE-754 is
 * sign-magnitude, so a bit-pattern subtraction would be meaningless across zero).
 */
function censusUlps(expected: readonly string[], got: readonly string[], width = 16): { total: number; exact: number; maxUlp: number; signMismatches: number } {
  let exact = 0;
  let maxUlp = 0;
  let signMismatches = 0;
  for (let i = 0; i < expected.length; i++) {
    const a = expected[i]!;
    const b = got[i]!;
    if (a === b) {
      exact += 1;
      continue;
    }
    const negativeA = Number.parseInt(a[0]!, 16) >= 8;
    const negativeB = Number.parseInt(b[0]!, 16) >= 8;
    if (negativeA !== negativeB) {
      signMismatches += 1;
      continue;
    }
    const ma = BigInt(`0x${a}`);
    const mb = BigInt(`0x${b}`);
    maxUlp = Math.max(maxUlp, Number(ma > mb ? ma - mb : mb - ma));
  }
  return { total: expected.length, exact, maxUlp, signMismatches };
}

/** Distance in representable doubles between two values given as 64-bit hex. */
function ulpDistance(a: string, b: string): number {
  const va = BigInt(`0x${a}`);
  const vb = BigInt(`0x${b}`);
  return Number(va > vb ? va - vb : vb - va);
}

function floatBits(v: number): string {
  const view = new DataView(new ArrayBuffer(4));
  view.setFloat32(0, v);
  return view.getUint32(0).toString(16).padStart(8, '0');
}

/** Bits -> `float`, for the probe's raw-bit dumps. */
function floatFromBits(bits: string): number {
  const view = new DataView(new ArrayBuffer(4));
  view.setUint32(0, Number.parseInt(bits, 16));
  return view.getFloat32(0);
}

