/**
 * Lane W1j/L16 — the vision camera, pinned against native `glGetFloatv` output.
 *
 * The goldens in `src/model/geometry/golden/nativeCameraVectors.ts` were produced by lane
 * W1e's probe (`src/model/geometry/native/glprobe.cpp`), which links the *native* library and
 * drives the real `gcamera`/`gpoint` through Apple's fixed-function GL, printing the matrices
 * GL itself computed. The fixtures (`GOLDEN_SCENES`, `GOLDEN_PERSPECTIVES`, `GOLDEN_MAT4`)
 * are replayed here through the port, comparing the f32 bit patterns.
 *
 * These goldens are read-only input: this lane never writes under `src/model/geometry/**`
 * or `oracle/**`.
 */

